class DataError(Exception):
    """A JSON or YAML file that cannot be read as the format requires."""

    def __init__(self, line: int, message: str) -> None:
        super().__init__(message)
        self.line = line
        self.message = message


def _unique_pairs(pairs: List[Tuple[str, Any]]) -> Dict[str, Any]:
    found: Dict[str, Any] = {}
    for key, value in pairs:
        if key in found:
            raise DataError(1, f"gives the key `{key}` twice in one object")
        found[key] = value
    return found


def _no_constant(name: str) -> Any:
    raise DataError(1, f"holds `{name}`, which JSON does not have")


class JsonNumber(decimal.Decimal):
    """A JSON number written with a point or an exponent, kept at the exact value it is written with and shown
    as written, as `0.29` or `1e2`; a whole number without either is read as an `int`, which is exact already."""

    text: str

    def __new__(cls, text: str) -> "JsonNumber":
        try:
            number = super().__new__(cls, text)
        except decimal.InvalidOperation:
            raise DataError(1, f"holds the number {shorten(text, 40)}, which is too large to be held exactly") from None
        number.text = text
        return number

    def __repr__(self) -> str:
        return self.text

    __str__ = __repr__


def json_integer(text: str) -> Any:
    """A JSON number without a point or an exponent: an `int`, or, with more digits than this Python turns into an
    `int` (4300 from Python 3.11 on), a JsonNumber that keeps all its digits."""
    try:
        return int(text)
    except ValueError:
        return JsonNumber(text)


def load_json(text: str) -> Any:
    """JSON as the format reads it: a key given twice, `NaN` and `Infinity` are errors, and a number keeps the
    exact value it is written with."""
    try:
        return json.loads(text, object_pairs_hook=_unique_pairs, parse_constant=_no_constant, parse_float=JsonNumber,
                          parse_int=json_integer)
    except json.JSONDecodeError as error:
        raise DataError(len(LINE_BREAK.findall(error.doc, 0, error.pos)) + 1, f"is not JSON: {error.msg}") from None
    except RecursionError:
        raise DataError(1, "is nested too deeply to be read") from None


def is_multiple(value: Any, divisor: Any) -> bool:
    """Whether dividing a number by a positive number gives a whole number, on their exact values.

    Each is a whole mantissa times a power of ten. Only the mantissas and the difference of the exponents
    are reckoned with, so a number such as `1e400000000` costs no more than its digits.
    """
    def parts(number: Any) -> Tuple[int, int, int]:
        """The whole mantissa, the exponent and the number of digits, without writing a long number as text."""
        sign, digits, exponent = decimal.Decimal(number).as_tuple()
        mantissa = int(decimal.Decimal((0, digits, 0)))
        return (-mantissa if sign else mantissa), exponent, len(digits)
    mantissa, exponent, size = parts(value)
    by, by_exponent, _ = parts(divisor)
    if mantissa == 0:
        return True
    shift = exponent - by_exponent
    if shift >= 0:
        return mantissa % by * pow(10, shift, by) % by == 0
    if -shift > size:
        return False  # the divisor is larger than the number, which is not zero
    return mantissa % (by * 10 ** -shift) == 0


# The tags of the JSON schema of YAML 1.2, to which OpenAPI limits a contract; the non-specific `!` resolves to them.
JSON_SCHEMA_TAGS = frozenset(["!"] + [f"tag:yaml.org,2002:{name}" for name in ("null", "bool", "int", "float", "str",
                                                                             "map", "seq")])
MERGE_TAG = "tag:yaml.org,2002:merge"
NUMBER_TAGS = {"tag:yaml.org,2002:int": "int", "tag:yaml.org,2002:float": "float"}
EXACT_IN_LIBFYAML = (-2 ** 63, 2 ** 64 - 1)  # the tagged integers libfyaml holds exactly
# The integers and floats of the core schema of YAML 1.2 (`.inf` and `.nan` aside).
YAML_INTEGER = re.compile(rb"[-+]?[0-9]+|0o[0-7]+|0x[0-9a-fA-F]+")
YAML_FLOAT = re.compile(rb"[-+]?(?:\.[0-9]+|[0-9]+(?:\.[0-9]*)?)(?:[eE][-+]?[0-9]+)?")
YAML_SPECIAL = re.compile(rb"[-+]?\.(?:inf|Inf|INF)|\.(?:nan|NaN|NAN)")
TAG_TOKEN = re.compile(rb"!(?:<[^>]*>|[^\s,\[\]{}]*)")
BLOCK_HEADER = re.compile(rb"((?:[ \t\r\n]|#[^\r\n]*)*[|>])([-+]?)([1-9])?([-+]?)")  # the header of a block scalar
ALIAS_TOKEN = re.compile(r"\*([^ \t\r\n,\[\]{}\ufeff]+)")  # a name ends only where YAML 1.2 ends it (6.9.2, 7.1)


def yaml_integer(text: str) -> int:
    """A YAML 1.2 integer from its digits, of any number of them: Python's limit on turning decimal text into an
    `int` (4300 digits from Python 3.11 on) is not met by way of a Decimal, which holds every digit."""
    if text[:2] in ("0o", "0x"):
        return int(text[2:], 8 if text[1] == "o" else 16)
    try:
        return int(text)
    except ValueError:
        return int(decimal.Decimal(text))


def yaml_number(written: bytes, kind: Optional[str], line: int) -> Any:
    """The number a scalar's text stands for (the written text of a plain scalar, the decoded text of a quoted one),
    `int` or `float` the kind its tag gives it, or None when the text is not one: an integer keeps all its digits, a
    float its exact value, as a JsonNumber. A tagged text that does not have the form of its tag, `.inf` and `.nan`
    aside, cannot be read."""
    if kind != "float" and YAML_INTEGER.fullmatch(written):
        return yaml_integer(written.decode("ascii"))
    if kind != "int" and YAML_FLOAT.fullmatch(written):
        try:
            return JsonNumber(written.decode("ascii"))
        except DataError as error:
            raise DataError(line, error.message) from None
    if kind is not None and not (kind == "float" and YAML_SPECIAL.fullmatch(written)):
        raise DataError(line, f"cannot be read as YAML: failed to create scalar with tag tag:yaml.org,2002:{kind}")
    return None


def yaml_text(written: bytes, libfyaml: Any) -> Optional[bytes]:
    """The text YAML decodes from a scalar as written after its tag, plain, quoted or block, with its escapes, folded
    lines and chomping: libfyaml reads it alone, as the value of a key, without an indentation of its own. So an
    indentation indicator of a block header is left out and libfyaml finds the indentation from the first line; a
    number libfyaml builds has no leading spaces in its content, so either way it is the same text. None when that is
    no text."""
    header = BLOCK_HEADER.match(written)
    if header and header.group(3):
        written = header.group(1) + header.group(2) + header.group(4) + written[header.end():]
    document = libfyaml.loads("k: !!str" + written.decode("utf-8"), collect_diag=True, create_markers=True)
    value = document.to_python() if document.get_marker() is not None else None  # no marker: diagnostics
    text = value.get("k") if isinstance(value, dict) else None
    return text.encode("utf-8", "surrogatepass") if isinstance(text, str) else None


def load_yaml(text: str, libfyaml: Any) -> Any:
    """A YAML file as YAML 1.2 reads it, through libfyaml, and only as plainly written.

    Each form that is not plain is reported with its reason: an anchor, an alias, the merge key `<<`, a tag outside
    the JSON schema of YAML 1.2, a key that is not a string (a list, a mapping, an empty or null key), a key given
    twice or two keys Python holds as one, no document, more than one. libfyaml shows an anchor only with
    `keep_anchors`, and an alias there is a node without a place of its own (`create_markers`). It decodes a
    `!!binary` scalar and does not show its tag, so a scalar whose text begins with `!` and has no tag is read as
    tagged: no scalar begins with `!` otherwise. Its diagnostics come back as data (`collect_diag`); the few it still
    writes to the descriptor of standard error are taken in and named in the report instead. A scalar that YAML 1.2
    resolves to a number is taken from its text, since libfyaml holds whole numbers only within 64 bits and floats only
    as doubles: a plain one from its written text, a tagged one from the text YAML decodes from it (yaml_text). A
    tagged number libfyaml does not build at all is reported as its diagnostic; where libfyaml holds a tagged integer
    exactly, the text must give the same value.
    """
    options = {"keep_anchors": True, "create_markers": True, "collect_diag": True}
    sys.stderr.flush()
    kept = os.dup(2)
    with tempfile.TemporaryFile() as written:
        os.dup2(written.fileno(), 2)
        try:
            document = libfyaml.loads(text, **options)
            documents = list(libfyaml.loads_all(text, **options)) if document.get_marker() is not None else []
        except ValueError as error:
            if str(error) == "No documents found in input":
                raise DataError(1, "holds no YAML document") from None
            written.seek(0)
            said = [line.strip() for line in written.read().decode("utf-8", "replace").splitlines() if line.strip()]
            raise DataError(1, f"cannot be read as YAML: {said[-1] if said else error}") from None
        finally:
            os.dup2(kept, 2)
            os.close(kept)
    if document.get_marker() is None:  # the diagnostics, which have no place in the text
        first = document.to_python()[0]
        line, column = first.get("line") or 1, first.get("column") or 1
        lines = split_lines(text[1:] if text.startswith("\ufeff") else text)  # a byte order mark is on no line
        alias = ALIAS_TOKEN.match(lines[line - 1], max(column - 2, 0)) if line <= len(lines) else None
        if first.get("message") == "Unable to resolve alias" and alias:
            raise DataError(line, f"uses the alias `*{one_line(alias.group(1))}`, which is not read; write the value out")
        raise DataError(line, f"cannot be read as YAML: {first.get('message')}")
    if len(documents) > 1:
        marker = documents[1].get_marker()
        raise DataError(marker[1] + 1 if marker else 1, "holds more than one YAML document")
    source = text.encode("utf-8")

    def build(node: Any, around: int) -> Any:
        marker = node.get_marker()
        anchor = node.get_anchor()
        if anchor is not None:
            line = marker[1] + 1 if marker else around  # where libfyaml begins the node: the anchored value or its tag
            raise DataError(line, f"sets the anchor `&{one_line(anchor)}`, which is not read; write the value out")
        if marker is None:
            raise DataError(around, "uses an alias, which is not read; write the value out")
        line = marker[1] + 1
        tag = node.get_tag()
        token = TAG_TOKEN.match(source, marker[0])
        collection = node.is_mapping() or node.is_sequence()
        if (tag is not None and tag not in JSON_SCHEMA_TAGS) or (tag is None and token and not collection):
            shown = token.group().decode("utf-8") if token else tag
            raise DataError(line, f"uses the tag `{shown}`, which is outside the JSON schema of YAML 1.2; it is not read")
        if node.is_sequence():
            return [build(item, line) for item in node]
        if not node.is_mapping():
            kind = NUMBER_TAGS.get(tag or "")
            number = None
            if token is None:  # a plain number by its written text; quoted or block, it is text
                number = yaml_number(source[marker[0]:marker[3]], None, line)
            elif kind:
                decoded = yaml_text(source[token.end():marker[3]], libfyaml)
                number = yaml_number(b"" if decoded is None else decoded, kind, line)
                built = node.to_python()
                if kind == "int" and EXACT_IN_LIBFYAML[0] <= number <= EXACT_IN_LIBFYAML[1] and built != number:
                    raise DataError(line, f"cannot be read as YAML: libfyaml reads the integer {number} as {built}")
            if number is not None:
                return number
            try:
                return node.to_python()
            except UnicodeDecodeError:
                raise DataError(line, "holds a value that is not UTF-8 text; it is not read") from None
        found: Dict[Any, Any] = {}
        seen: List[Tuple[Any, str]] = []
        try:
            pairs = list(node.items())
        except TypeError as error:  # libfyaml cannot hand out a mapping that has a list or a mapping as a key
            kind = "a list" if "'sequence'" in str(error) else "a mapping" if "'mapping'" in str(error) else "a list or a mapping"
            raise DataError(line, f"holds a key that is {kind}, not a string; it is not read") from None
        for key_node, value_node in pairs:
            key_marker = key_node.get_marker()
            key_line = key_marker[1] + 1 if key_marker else line
            plain = source[key_marker[0]:key_marker[3]] if key_marker else b""
            if key_node.get_tag() == MERGE_TAG or (plain == b"<<" and key_node.is_string()):
                raise DataError(key_line, "uses the merge key `<<`, which is not read; write the keys out")
            key = build(key_node, line)
            if key is None:
                raise DataError(key_line, "holds a key that is empty or null, not a string; it is not read")
            shown = key if isinstance(key, str) else plain.decode("utf-8")
            same = next((other for other in seen if other[0] == key), None)
            if same is not None:
                if type(same[0]) is type(key):
                    raise DataError(key_line, f"gives the key `{shown}` twice in one mapping")
                # Equal in Python, such as 1, true and 1.0, but two keys in YAML: a dict holds only one.
                raise DataError(key_line, f"holds the keys `{same[1]}` and `{shown}` in one mapping, which the checker "
                                "cannot hold apart; it is not read")
            seen.append((key, shown))
            found[key] = build(value_node, key_line)
        return found

    return build(document, 1)


def decimal_digits(number: int) -> str:
    """A whole number as its decimal digits, of any number of them, without Python's limit on `str` of an `int`."""
    return str(decimal.Decimal(number))


def escape_token(key: Any) -> str:
    """A key as a token of a JSON Pointer; a whole number by its decimal digits."""
    return (decimal_digits(key) if type(key) is int else str(key)).replace("~", "~0").replace("/", "~1")


def find_keys(data: Any, key: str) -> List[Tuple[str, Any]]:
    """Every object that holds `key`, with its JSON Pointer and the value of the key, in order."""
    found: List[Tuple[str, Any]] = []
    waiting: List[Tuple[str, Any]] = [("", data)]
    while waiting:
        pointer, value = waiting.pop()
        if isinstance(value, dict):
            if key in value:
                found.append((pointer, value[key]))
            waiting.extend(reversed([(f"{pointer}/{escape_token(name)}", item) for name, item in value.items()]))
        elif isinstance(value, list):
            waiting.extend(reversed([(f"{pointer}/{index}", item) for index, item in enumerate(value)]))
    return found


def find_refs(data: Any) -> List[Tuple[str, str]]:
    """Every key `$ref` with a string value, with the JSON Pointer of the object that holds it, in order."""
    return [(pointer, value) for pointer, value in find_keys(data, "$ref") if isinstance(value, str)]


def place(pointer: str) -> str:
    return f"`{pointer}`" if pointer else "the top level"


# Characters that would break a report out of its one line, hide in it, or cannot be written (lone surrogates).
CONTROL = re.compile("[\\x00-\\x1f\\x7f-\\x9f\\u2028\\u2029\\ud800-\\udfff]")


def one_line(text: str) -> str:
    """Text from a JSON or YAML file as a report or `trace.md` shows it: each character of CONTROL escaped as
    JSON writes it."""
    return CONTROL.sub(lambda found: json.dumps(found.group())[1:-1], text)


class LoneSurrogate(Exception):
    """A text with a lone surrogate that a pattern would have to be matched against: regress takes no such text."""

    def __init__(self, text: str) -> None:
        super().__init__(text)
        self.text = text

    def reason(self) -> str:  # the report escapes the lone surrogate and control characters, and nothing else
        return f"the text `{shorten(self.text, 80)}` holds a lone surrogate, which no pattern can be matched against"


def ecma_pattern(pattern: str) -> Optional[str]:
    """A pattern as regress takes it, read as ECMA-262 reads it in its Unicode mode: a lone surrogate is a code point
    of the pattern, written as the escape `\\u{D800}`, when an even number of backslashes stands directly before it;
    after an odd number it is the operand of an escape, which ECMA-262 does not accept there, and there is None."""
    parts: List[str] = []
    start = 0
    for found in SURROGATE.finditer(pattern):
        before = pattern[start:found.start()]
        if (len(before) - len(before.rstrip("\\"))) % 2:
            return None
        parts.append(f"{before}\\u{{{ord(found.group()):04X}}}")
        start = found.end()
    return "".join(parts) + pattern[start:]


def decode_percent(text: str) -> Optional[str]:
    """Percent-encoding decoded as UTF-8, strictly; None when the bytes it gives are no UTF-8."""
    try:
        return unquote_to_bytes(text).decode("utf-8")
    except UnicodeDecodeError:
        return None


def follow_pointer(document: Any, fragment: str) -> Tuple[Any, Optional[str], Optional[str]]:
    """Follow a fragment as a JSON Pointer by RFC 6901, in contracts and in schemas alike.

    Returns the value it leads to, why the fragment is no JSON Pointer, and the token at which it finds
    nothing; only one of the last two is set when it does not lead to a value. A step into a list takes
    only an array index: `0`, or a digit 1-9 followed by digits.
    """
    pointer = decode_percent(fragment)
    malformed = f"has the fragment `#{fragment}`, which is no JSON Pointer"
    if pointer is None:
        return None, f"{malformed}: its percent-encoding does not decode as UTF-8", None
    if not pointer:
        return document, None, None
    if not pointer.startswith("/"):
        return None, malformed, None
    value = document
    for raw in pointer[1:].split("/"):
        if re.search(r"~(?![01])", raw):
            return None, f"{malformed}: `~` stands only in `~0` and `~1`", None
        token = raw.replace("~1", "/").replace("~0", "~")
        if isinstance(value, dict):
            if token in value:
                value = value[token]
                continue
            # A key that YAML reads as a whole number matches the token of its digits.
            if re.fullmatch(r"0|-?[1-9][0-9]*", token):  # the token as a number, not every key as text
                number = int(decimal.Decimal(token))
                numbers = [key for key in value if type(key) is int and key == number]
            else:
                numbers = []
            if numbers:
                value = value[numbers[0]]
                continue
        elif (isinstance(value, list) and re.fullmatch(r"0|[1-9][0-9]*", token)
              and len(token) <= len(str(len(value))) and int(token) < len(value)):  # no int of a token too long to count
            value = value[int(token)]
            continue
        return None, None, raw
    return value, None, None


# The keywords of JSON Schema 2020-12 whose value, items or values are subschemas, as the `referencing`
# library crawls them (with `definitions`, which the 2020-12 meta-schema keeps).
SUBSCHEMA_IN_VALUE = frozenset((
    "additionalProperties", "contains", "contentSchema", "else", "if", "items", "not", "propertyNames", "then",
    "unevaluatedItems", "unevaluatedProperties",
))
SUBSCHEMA_IN_LIST = frozenset(("allOf", "anyOf", "oneOf", "prefixItems"))
SUBSCHEMA_IN_MAP = frozenset(("$defs", "definitions", "dependentSchemas", "patternProperties", "properties"))


# A URI-reference by RFC 3986, section 4.1, as one pattern. An IP-literal in brackets is checked apart.
_UNRESERVED, _SUB_DELIMS, _PCT = r"A-Za-z0-9\-._~", r"!$&'()*+,;=", r"%[0-9A-Fa-f]{2}"
_PCHAR = rf"(?:[{_UNRESERVED}{_SUB_DELIMS}:@]|{_PCT})"
_AUTHORITY = (rf"(?:(?:[{_UNRESERVED}{_SUB_DELIMS}:]|{_PCT})*@)?"
              rf"(?:\[[^\[\]/?#@]*\]|(?:[{_UNRESERVED}{_SUB_DELIMS}]|{_PCT})*)(?::[0-9]*)?")
_ABSOLUTE_PATH = rf"/(?:{_PCHAR}+(?:/{_PCHAR}*)*)?"
_TAIL = rf"(?:\?(?:{_PCHAR}|[/?])*)?(?:#(?:{_PCHAR}|[/?])*)?"
URI_REFERENCE = re.compile(
    rf"(?:[A-Za-z][A-Za-z0-9+\-.]*:(?://{_AUTHORITY}(?:/{_PCHAR}*)*|{_ABSOLUTE_PATH}|{_PCHAR}+(?:/{_PCHAR}*)*|)"
    rf"|(?://{_AUTHORITY}(?:/{_PCHAR}*)*|{_ABSOLUTE_PATH}|(?:[{_UNRESERVED}{_SUB_DELIMS}@]|{_PCT})+(?:/{_PCHAR}*)*|))"
    rf"{_TAIL}"
)
IP_FUTURE = re.compile(rf"v[0-9A-Fa-f]+\.[{_UNRESERVED}{_SUB_DELIMS}:]+")


def uri_reference(text: str) -> bool:
    """Whether a text is a URI-reference by RFC 3986; an IP-literal must be an IPv6 address or an IPvFuture."""
    if not URI_REFERENCE.fullmatch(text):
        return False
    for literal in re.findall(r"\[([^\]]*)\]", text):
        if IP_FUTURE.fullmatch(literal):
            continue
        try:
            ipaddress.IPv6Address(literal)
        except ValueError:
            return False
        if "%" in literal:
            return False  # a zone id, which RFC 3986 does not have
    return True


# The five parts of a URI reference, by RFC 3986, appendix B: scheme, authority, path, query and fragment.
# A part that is missing is None; the path is always there, if empty.
URI_PARTS = re.compile(r"(?:([^:/?#]+):)?(?://([^/?#]*))?([^?#]*)(?:\?([^#]*))?(?:#(.*))?", re.DOTALL)


def remove_dot_segments(path: str) -> str:
    """RFC 3986, section 5.2.4."""
    output: List[str] = []
    while path:
        if path.startswith("../"):
            path = path[3:]
        elif path.startswith("./"):
            path = path[2:]
        elif path.startswith("/./"):
            path = path[2:]
        elif path == "/.":
            path = "/"
        elif path.startswith("/../") or path == "/..":
            path = "/" + path[4:]
            if output:
                output.pop()
        elif path in (".", ".."):
            path = ""
        else:
            segment = re.match(r"/?[^/]*", path).group()
            output.append(segment)
            path = path[len(segment):]
    return "".join(output)


def resolve_uri(base: str, ref: str) -> str:
    """A reference read against a base by RFC 3986, section 5.2, in the same way for every scheme.

    The standard reads a reference against an absolute base. The `$id` of a top level may be relative, and is
    read as written: the same steps apply to it, and a path that it leaves relative stays relative.
    """
    scheme, authority, path, query, fragment = URI_PARTS.fullmatch(ref).groups()
    if scheme is None:
        base_scheme, base_authority, base_path, base_query, _ = URI_PARTS.fullmatch(base).groups()
        scheme = base_scheme
        if authority is None:
            authority = base_authority
            if not path:
                path = base_path
                query = base_query if query is None else query
            elif not path.startswith("/"):
                if base_authority is not None and not base_path:
                    path = "/" + path
                else:
                    path = base_path[:base_path.rfind("/") + 1] + path
    resolved = remove_dot_segments(path)
    if resolved.startswith("/") and not path.startswith("/"):
        resolved = resolved[1:]  # a relative path stays relative
    return ((f"{scheme}:" if scheme is not None else "") + (f"//{authority}" if authority is not None else "")
            + resolved + (f"?{query}" if query is not None else "") + (f"#{fragment}" if fragment is not None else ""))


def join_uri(base: str, ref: str) -> Tuple[str, str]:
    """A reference read against a base by RFC 3986: what it names without its fragment, and the fragment."""
    named, _, fragment = resolve_uri(base, ref).partition("#")
    return named, fragment


def value_at(document: Any, pointer: str) -> Any:
    """The value at a JSON Pointer that the walk of a schema wrote, and that leads to a value."""
    for raw in pointer.split("/")[1:]:
        token = raw.replace("~1", "/").replace("~0", "~")
        document = document[int(token)] if isinstance(document, list) else document[token]
    return document


# The keys of a subschema whose string value is a reference that the checker resolves.
REFERENCE_KEYS = ("$ref", "$dynamicRef")

# What the checker gives the validator's library as the `$id` of each resource, and its references are
# rewritten to: `keelblocks-resource:` and a number. The library then never reads one reference against a
# base itself, which its URL joining does only for some schemes; it reads every reference as the checker does.
RESOURCE_PREFIX = "keelblocks-resource:"


def walk_schema(
    top: Any, base: str,
) -> Tuple[List[Tuple[str, str, str, str]], List[Tuple[str, str, Any]], List[Tuple[str, str]]]:
    """Read a schema file as JSON Schema 2020-12 gives its bases; `base` is the `$id` of the top level.

    Returns every key `$ref` or `$dynamicRef` with a string value in a subschema (its pointer, the key, the
    reference, the base it is read against), every subschema below the top level with an `$id` (its pointer,
    what the `$id` names, the subschema), and what cannot be read (pointer, why). Subschemas are the values of
    the keywords above; everything else is data, which holds no keyword and is not read.
    """
    refs: List[Tuple[str, str, str, str]] = []
    ids: List[Tuple[str, str, Any]] = []
    odd: List[Tuple[str, str]] = []
    waiting: List[Tuple[Any, str, str]] = [(top, "", base)]
    while waiting:
        value, at, here = waiting.pop()
        if not isinstance(value, dict):
            continue
        if at:  # the `$id` of the top level is the base itself, not read against anything
            # A `$schema` that is no text is the meta-schema's to report, and the schema is set aside then.
            if isinstance(value.get("$schema"), str) and value["$schema"] != DIALECT:
                odd.append((at, f"`$schema` {shorten(json.dumps(value['$schema']))} is no dialect whose `$id` and "
                                "`$ref` the checker reads"))
            ident = value.get("$id")
            if isinstance(ident, str):
                if not uri_reference(ident):
                    odd.append((at, f"`$id` \"{ident}\" cannot be read as a URI reference"))
                else:
                    named, fragment = join_uri(here, ident)
                    if fragment:
                        odd.append((at, f"`$id` \"{ident}\" has a fragment"))
                    else:
                        here = named
                        ids.append((at, named, value))
        refs.extend((at, key, value[key], here) for key in REFERENCE_KEYS if isinstance(value.get(key), str))
        found: List[Tuple[Any, str, str]] = []
        for key, item in value.items():
            pointer = f"{at}/{escape_token(key)}"
            if key in SUBSCHEMA_IN_VALUE:
                found.append((item, pointer, here))
            elif key in SUBSCHEMA_IN_LIST and isinstance(item, list):
                found.extend((sub, f"{pointer}/{index}", here) for index, sub in enumerate(item))
            elif key in SUBSCHEMA_IN_MAP and isinstance(item, dict):
                found.extend((sub, f"{pointer}/{escape_token(name)}", here) for name, sub in item.items())
            # Every other value is data: an `$id`, a `$ref` or a `$dynamicRef` there is no keyword.
        waiting.extend(reversed(found))
    return refs, ids, odd


def shorten(text: str, size: int = 160) -> str:
    return text if len(text) <= size else text[:size - 3] + "..."


def with_article(word: str) -> str:
    return ("an " if word[:1] in "aeiou" else "a ") + word


def describe_errors(errors: List[Any]) -> str:
    """The first errors of a validation, ordered by their place, each with its JSON path; an error that the
    meta-schema gives several times, through its several parts, is shown once."""
    distinct = sorted({(tuple(str(part) for part in error.absolute_path), error.message, error.json_path)
                       for error in errors})
    text = "; ".join(f"{path}: {shorten(message)}" for _, message, path in distinct[:SHOWN_ERRORS])
    more = len(distinct) - SHOWN_ERRORS
    return text + (f"; and {more} more" if more > 0 else "")


