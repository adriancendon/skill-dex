# A file name that is not UTF-8, as some file systems allow, reaches Python with a lone surrogate for each such byte
# (PEP 383); it could not be written.
SURROGATE = re.compile("[\\ud800-\\udfff]")


def name_shown(text: str) -> str:
    """Text that names a file, as output shows it: each lone surrogate escaped as JSON writes it, as reports escape
    text; text in UTF-8 unchanged."""
    return SURROGATE.sub(lambda found: json.dumps(found.group())[1:-1], text)



def open_package(root: Path) -> Optional[Package]:
    if not (root / "decisions.md").is_file():
        print(f"keelblocks: {root} is not a package (no decisions.md); run init first", file=sys.stderr)
        return None
    libraries = None
    if (root / "architecture.md").is_file():
        libraries, missing = full_tier_libraries()
        if libraries is None:
            print(f"keelblocks: {root} is a full package (it holds architecture.md), and {needs_libraries(missing)}",
                  file=sys.stderr)
            return None
    package = Package(root, libraries)
    package.read()
    return package


def cmd_check(root: Path, state_budget: int) -> int:
    package = open_package(root)
    if package is None:
        return 2
    package.check(state_budget)
    problems = sorted(set(package.problems), key=lambda p: (p.rel, p.line, p.rule, p.message))
    for problem in problems:
        print(name_shown(f"{(root / problem.rel).as_posix()}:{problem.line}: {problem.rule} {problem.message}"))
    if problems:
        print(f"check: {len(problems)} problem(s)")
        return 1
    print(
        f"check: ok ({len(package.of_kind('REQ'))} requirements, "
        f"{len(package.of_kind('D'))} decisions, {len(package.of_kind('OP'))} open points)"
    )
    return 0


def replace_file(path: Path, text: str) -> None:
    """Put a new file in place of the old one, so that another name of the old file keeps its content."""
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    descriptor = os.open(str(temporary), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o666)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.replace(str(temporary), str(path))
    except BaseException:
        if temporary.exists():
            temporary.unlink()
        raise


def cmd_index(root: Path, check_only: bool) -> int:
    package = open_package(root)
    if package is None:
        return 2
    wanted = {"trace.md": build_trace(package)}
    if package.tier is not None:
        wanted["views.md"] = build_views(package)
    current: Dict[str, Optional[str]] = {}
    for name in wanted:
        path = root / name
        if path.is_symlink():
            print(
                f"keelblocks: {path.as_posix()} is a link; index does not write through links. "
                "Replace it with a regular file or remove it.",
                file=sys.stderr,
            )
            return 2 if not check_only else 1
        current[name] = path.read_text(encoding="utf-8", errors="replace") if path.is_file() else None
    stale = [name for name in wanted if current[name] != wanted[name]]
    if check_only or not stale:
        for name in wanted:
            print(f"index: {name} is missing or out of date: run index" if name in stale else f"index: {name} is up to date")
        return 1 if stale else 0
    for name in stale:
        text = current[name]
        if text is not None and not text.startswith(GENERATED_PREFIX):
            print(
                f"keelblocks: {(root / name).as_posix()} exists and was not generated by keelblocks; "
                "it is left untouched. Move or rename it, then run index.",
                file=sys.stderr,
            )
            return 2
    for name in stale:
        replace_file(root / name, wanted[name])
        print(f"index: wrote {(root / name).as_posix()}")
    return 0


def cmd_init(root: Path, tier: str) -> int:
    script = Path(__file__).resolve()
    templates = script.parent.parent / "assets" / "templates"
    if not templates.is_dir():
        print(
            "keelblocks: init needs the templates of the keelblocks-start skill; "
            "run the script from that skill's scripts/ folder",
            file=sys.stderr,
        )
        return 2
    if tier == "full" or (root / "architecture.md").is_file():
        libraries, missing = full_tier_libraries()
        if libraries is None:
            print(f"keelblocks: init writes nothing: {root} is to be a full package, and {needs_libraries(missing)}",
                  file=sys.stderr)
            return 2
    root.mkdir(parents=True, exist_ok=True)
    for source in sorted(p for p in templates.rglob("*") if p.is_file()):
        target = root / source.relative_to(templates)
        if target.exists() or target.is_symlink():
            print(f"init: kept existing {target.as_posix()}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        print(f"init: wrote {target.as_posix()}")
    requirements = root / "requirements"
    if requirements.is_symlink():
        print(f"init: kept {requirements.as_posix()}, which is a link")
    elif not requirements.is_dir():
        requirements.mkdir()
        print(f"init: created {requirements.as_posix()}/")
    tools = root / "tools"
    tool = tools / "keelblocks.py"
    if tools.is_symlink():
        print(
            f"init: kept {tools.as_posix()}, which is a link; init does not write through links. "
            "Copy the script there by hand if it is missing."
        )
    elif tool.exists() or tool.is_symlink():
        print(f"init: kept existing {tool.as_posix()}; copy the script by hand to upgrade it")
    else:
        tools.mkdir(exist_ok=True)
        shutil.copyfile(script, tool)
        print(f"init: wrote {tool.as_posix()}")
    if tier == "full":
        # The full tier: architecture.md and c4.md from their templates, and the folder of the ADRs.
        for source in sorted(p for p in (script.parent.parent / "assets" / "templates-full").iterdir() if p.is_file()):
            target = root / source.name
            if target.exists() or target.is_symlink():
                print(f"init: kept existing {target.as_posix()}")
                continue
            shutil.copyfile(source, target)
            print(f"init: wrote {target.as_posix()}")
        adr = root / "adr"
        if adr.is_symlink():
            print(f"init: kept {adr.as_posix()}, which is a link")
        elif not adr.is_dir():
            adr.mkdir()
            print(f"init: created {adr.as_posix()}/")
        # A copy the package kept from an earlier keelblocks would not read the full tier.
        differing = [
            target.as_posix() for target, source in ((tool, script), (root / "README.md", templates / "README.md"))
            if target.is_file() and target.read_bytes() != source.read_bytes()
        ]
        if differing:
            print(
                f"init: {' and '.join(differing)} differ from this keelblocks; upgrade both copies before the full tier: "
                "replace tools/keelblocks.py and README.md with the skill's copies, then run index and check with "
                "the package's tools/keelblocks.py"
            )
    return cmd_index(root, check_only=False)


def cmd_rules() -> int:
    for rule, meaning in RULES.items():
        print(f"{rule}  {meaning}")
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="keelblocks",
        description="Check and index a Markdown requirements package.",
    )
    parser.add_argument("--version", action="version", version=f"keelblocks {__version__}")
    commands = parser.add_subparsers(dest="command", required=True)

    def with_root(name: str, text: str) -> argparse.ArgumentParser:
        sub = commands.add_parser(name, help=text, description=text)
        sub.add_argument("--root", default="spec", help="package folder (default: spec)")
        return sub

    check = with_root("check", "Report every rule the package breaks; exit 1 if any.")
    check.add_argument(
        "--state-budget", type=int, default=STATE_BUDGET_BYTES,
        help=f"size budget of state.md in bytes (default: {STATE_BUDGET_BYTES})",
    )
    index = with_root("index", "Write trace.md, and views.md for a full package, from the sources.")
    index.add_argument("--check", action="store_true", help="only report whether the generated files are current")
    init = with_root("init", "Create a new package from the templates and copy this script into it.")
    init.add_argument(
        "--tier", choices=("core", "full"), default="core",
        help="core, or full for a package with architecture, C4 views, ADRs, schemas and API contracts "
        "(default: core)",
    )
    commands.add_parser("rules", help="List the rules.", description="List the rules.")

    args = parser.parse_args(argv)
    if args.command == "rules":
        return cmd_rules()
    root = Path(args.root)
    try:
        if args.command == "check":
            return cmd_check(root, args.state_budget)
        if args.command == "index":
            return cmd_index(root, args.check)
        return cmd_init(root, args.tier)
    except (InputError, OSError) as error:
        print(f"keelblocks: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
