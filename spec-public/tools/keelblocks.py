class FullTier:
    """The pieces of a full package beyond its entries: architecture, C4 tables, schemas and contracts."""

    def __init__(self, package: Package, libraries: Libraries) -> None:
        self.package = package
        self.root = package.root
        self.libraries = libraries
        self.applies: Dict[str, Tuple[int, bool]] = {}  # piece: line of its row, whether it applies
        self.elements: Dict[str, Element] = {}
        self.declared: Set[str] = set()  # ids of element rows reported for their cells or their id
        self.elements_read = False
        self.relationships: List[Relationship] = []
        self.schemas: Dict[str, Schema] = {}
        self.by_key: Dict[str, Schema] = {}
        self.instances: List[Tuple[str, str, bool]] = []  # file, schema name, meant to be valid
        self.contracts: List[Contract] = []
        self.data: Dict[str, Any] = {}
        self.registry: Any = None
        self.meta: Any = None  # a validator for the meta-schema of JSON Schema 2020-12, made once
        self.validator: Any = None  # the validator class with exact numbers, made once
        self.tokens: Dict[str, str] = {}  # what a resource is named: what the validator's library gets for it
        # What an `$id` names (of a schema or of a subschema in one): its schema, the subschema, its pointer.
        self.resources: Dict[str, Tuple[Schema, Any, str]] = {}

    def report(self, rel: str, line: int, rule: str, message: str) -> None:
        # A report is one line that can be written: a control character or a lone surrogate from the files, such
        # as a line break in a `$ref`, is shown escaped, as JSON writes it.
        self.package.report(rel, line, rule, one_line(message))

    def read(self) -> None:
        self._read_architecture()
        self._read_c4()
        self._read_schemas()
        self._read_contracts()
        self._check_applicability()

    def _data(self, rel: str) -> Any:
        """A JSON or YAML file of the package, read once: JSON by its name, YAML otherwise."""
        if rel not in self.data:
            raw = (self.root / rel).read_bytes()
            try:
                text = raw.decode("utf-8")
            except UnicodeDecodeError as error:
                self.data[rel] = DataError(1, f"is not valid UTF-8 (first bad byte at offset {error.start})")
            else:
                try:
                    self.data[rel] = load_json(text) if rel.endswith(".json") else self._load_yaml(text)
                except DataError as error:
                    self.data[rel] = error
        found = self.data[rel]
        if isinstance(found, DataError):
            raise found
        return found

    def _load_yaml(self, text: str) -> Any:
        try:
            return load_yaml(text, self.libraries.libfyaml)
        except RecursionError:
            raise DataError(1, "is nested too deeply to be read") from None

    def _lines(self, rel: str) -> List[Tuple[int, str, bool]]:
        return list(read_lines((self.root / rel).read_text(encoding="utf-8")))

    def _table(self, rel: str, part: Part, header: Tuple[str, ...], rule: str) -> Optional[List[Tuple[int, List[str]]]]:
        """The rows below the header and separator of the one table of a part, or None if it has none."""
        rows = [(number, table_cells(text)) for number, text, fenced in part.body if not fenced and text.startswith("|")]
        if not rows:
            self.report(rel, part.line, rule, f"`## {part.title}` holds no table")
            return None
        if tuple(rows[0][1]) != header:
            self.report(
                rel, rows[0][0], rule,
                f"the table under `## {part.title}` must begin with the header `| {' | '.join(header)} |`",
            )
            return None
        separator = rows[1][1] if len(rows) > 1 else []
        if len(separator) != len(header) or not all(SEPARATOR_CELL.fullmatch(text) for text in separator):
            self.report(
                rel, rows[1][0] if len(rows) > 1 else rows[0][0], rule,
                f"the header of the table under `## {part.title}` must be followed by a separator row "
                f"such as `|{'---|' * len(header)}`",
            )
            return None
        return rows[2:]

    # -- architecture.md -------------------------------------------------------

    def _read_architecture(self) -> None:
        rel = "architecture.md"
        lines = self._lines(rel)
        parts = level2_parts(lines)
        found: Dict[str, List[Part]] = {}
        for part in parts:
            if part.title in ARCHITECTURE_PARTS:
                found.setdefault(part.title, []).append(part)
        for title in ARCHITECTURE_PARTS:
            if title not in found:
                self.report(rel, 1, "ARC01", f"`## {title}` is missing")
            for extra in found.get(title, [])[1:]:
                first = found[title][0].line
                self.report(rel, extra.line, "ARC01", f"`## {title}` stands twice; it stands first at line {first}")
        firsts = sorted((same[0] for same in found.values()), key=lambda part: part.line)
        for before, after in zip(firsts, firsts[1:]):
            if ARCHITECTURE_PARTS.index(after.title) < ARCHITECTURE_PARTS.index(before.title):
                self.report(
                    rel, after.line, "ARC01",
                    f"`## {after.title}` stands after `## {before.title}`; the parts go in the order of the format",
                )
        for part in parts:
            if part.title in ARCHITECTURE_PARTS[1:] and not any(text.strip() for _, text, _ in part.body):
                self.report(
                    rel, part.line, "ARC02",
                    f"`## {part.title}` is empty; write it, or `{NOT_APPLICABLE}` with the reason",
                )
        for number, text, fenced in lines:
            if not fenced and text.startswith(NOT_APPLICABLE) and not text[len(NOT_APPLICABLE):].strip():
                self.report(rel, number, "ARC02", f"`{NOT_APPLICABLE}` needs the reason after the colon")
        if len(found.get("Applicability", [])) == 1:
            self._read_applicability(rel, found["Applicability"][0])

    def _read_applicability(self, rel: str, part: Part) -> None:
        rows = self._table(rel, part, APPLICABILITY_HEADER, "ARC03")
        if rows is None:
            return
        seen: Dict[str, int] = {}
        stated: Dict[str, Tuple[int, bool]] = {}
        for line, cells in rows:
            if len(cells) != len(APPLICABILITY_HEADER):
                self.report(rel, line, "ARC03", f"the row has {len(cells)} cells; the header has 3")
                continue
            piece, applies, reason = cells
            if piece not in PIECES:
                self.report(rel, line, "ARC03", f"`{piece}` is no piece; the pieces are `Data schemas` and `API contracts`")
                continue
            if piece in seen:
                self.report(rel, line, "ARC03", f"`{piece}` has a row already at line {seen[piece]}")
                stated.pop(piece, None)
                continue
            seen[piece] = line
            if applies not in ("yes", "no"):
                value = f"`{applies}`" if applies else "empty"
                self.report(rel, line, "ARC03", f"`Applies` of `{piece}` is {value}; write `yes` or `no`")
            elif applies == "no" and not reason:
                self.report(rel, line, "ARC03", f"`{piece}` does not apply, and `Reason` must say why")
            else:
                stated[piece] = (line, applies == "yes")
        for piece in PIECES:
            if piece not in seen:
                self.report(rel, part.line, "ARC03", f"`## {part.title}` has no row for `{piece}`")
        self.applies = stated

    def _check_applicability(self) -> None:
        for piece, (line, applies) in self.applies.items():
            folder = PIECES[piece]
            if applies:
                suffixes = PIECE_FILES[folder]
                if not any(
                    name.endswith(suffixes) and (self.root / folder / name).is_file()
                    for name in self._names(self.root / folder)
                ):
                    self.report(
                        "architecture.md", line, "ARC04",
                        f"`{piece}` applies, but {folder}/ holds no file ending in {' or '.join(suffixes)}",
                    )
                continue
            files = self._all_files(folder)
            if files:
                self.report(
                    "architecture.md", line, "ARC04",
                    f"`{piece}` does not apply, but {folder}/ holds {len(files)} file(s), {files[0]} first",
                )

    @staticmethod
    def _names(folder: Path) -> List[str]:
        """The names in a folder that are read: all but those that start with a dot."""
        if not folder.is_dir():
            return []
        return [name for name in sorted(os.listdir(str(folder))) if not name.startswith(".")]

    def _all_files(self, folder: str) -> List[str]:
        """Every file in a folder of the package and in the folders below it, links followed once."""
        found: List[str] = []
        seen: Set[str] = set()
        waiting = [folder]
        while waiting:
            rel = waiting.pop(0)
            real = os.path.realpath(str(self.root / rel))
            if real in seen:
                continue
            seen.add(real)
            for name in self._names(self.root / rel):
                inner = f"{rel}/{name}"
                if (self.root / inner).is_dir():
                    waiting.append(inner)
                else:
                    found.append(inner)
        return found

    # -- c4.md -------------------------------------------------------------------

    def _read_c4(self) -> None:
        rel = "c4.md"
        if not (self.root / rel).is_file():
            return  # PKG02
        parts = level2_parts(self._lines(rel))
        tables: Dict[str, Optional[List[Tuple[int, List[str]]]]] = {}
        for title, header in (("Elements", ELEMENTS_HEADER), ("Relationships", RELATIONSHIPS_HEADER)):
            same = [part for part in parts if part.title == title]
            tables[title] = None
            if not same:
                self.report(rel, 1, "MDL01", f"`## {title}` is missing")
            elif len(same) > 1:
                for extra in same[1:]:
                    self.report(rel, extra.line, "MDL01", f"`## {title}` stands twice; it stands first at line {same[0].line}")
            else:
                tables[title] = self._table(rel, same[0], header, "MDL01")
        elements = tables["Elements"]
        if elements is not None:
            self.elements_read = True
            self._read_elements(rel, elements)
            if not any(element.type == "software_system" for element in self.elements.values()):
                line = next(part.line for part in parts if part.title == "Elements")
                self.report(rel, line, "ELM04", "c4.md has no element of type `software_system`")
        if tables["Relationships"] is not None:
            self._read_relationships(rel, tables["Relationships"])

    def _read_elements(self, rel: str, rows: List[Tuple[int, List[str]]]) -> None:
        for line, cells in rows:
            if len(cells) != len(ELEMENTS_HEADER):
                self.report(rel, line, "ELM01", f"the row has {len(cells)} cells; the header has {len(ELEMENTS_HEADER)}")
                self.declared.add(cells[0])
                continue
            ident, kind, name, parent, technology, description = cells
            if not ELEMENT_ID.fullmatch(ident):
                self.report(
                    rel, line, "ELM01",
                    f"`{ident}` is no element id: a lower-case letter, then lower-case letters, digits and hyphens",
                )
                self.declared.add(ident)
                continue
            if ident in self.elements:
                self.report(rel, line, "ELM01", f"`{ident}` is the id of the element at line {self.elements[ident].line}")
                continue
            if kind not in ELEMENT_TYPES:
                self.report(rel, line, "ELM01", f"{ident}: `{kind}` is no type; the types are {', '.join(ELEMENT_TYPES)}")
            for column, text in (("Name", name), ("Description", description)):
                if not text:
                    self.report(rel, line, "ELM01", f"{ident}: `{column}` is empty")
            self.elements[ident] = Element(
                ident, kind if kind in ELEMENT_TYPES else None, name, parent, technology, description, line
            )
        for element in self.elements.values():
            self._check_parent(rel, element)
            if element.type in INNER_TYPES and not element.technology:
                self.report(rel, element.line, "ELM03", f"{element.id}: a {element.type} needs `Technology`")

    def _check_parent(self, rel: str, element: Element) -> None:
        if element.type is None:
            element.fits = False  # not judged; such an element is left out of the views
            return
        wanted = PARENT_TYPES.get(element.type)
        if wanted is None:
            if element.parent:
                element.fits = False
                self.report(
                    rel, element.line, "ELM02", f"{element.id}: {with_article(element.type)} has no parent; leave `Parent` empty"
                )
            return
        parent = self.elements.get(element.parent)
        if not element.parent:
            message = f"{element.id}: a {element.type} needs the id of its {wanted} in `Parent`"
        elif parent is None:
            message = "" if element.parent in self.declared else (
                f"{element.id}: `Parent` names `{element.parent}`, which is no element of the table"
            )
        elif parent.type is None:
            message = ""  # its type is unknown, so whether it fits is not judged
        elif parent.type != wanted:
            message = (
                f"{element.id}: `Parent` names `{parent.id}`, {with_article(parent.type)}; the parent of a {element.type} "
                f"is a {wanted}"
            )
        else:
            return
        element.fits = False
        if message:
            self.report(rel, element.line, "ELM02", message)

    def _parent_of(self, element: Element) -> Optional[Element]:
        """The element a container or component is inside, when its `Parent` names one of the type it asks for."""
        parent = self.elements.get(element.parent) if element.type in INNER_TYPES else None
        return parent if parent is not None and parent.type == PARENT_TYPES[element.type or ""] else None

    def inside(self, inner: str, outer: str) -> bool:
        """Whether one element is inside another: a container in the system its `Parent` names, a component
        in the container its `Parent` names and in that container's system."""
        parent = self._parent_of(self.elements[inner])
        if parent is None:
            return False
        system = self._parent_of(parent) if parent.type == "container" else None
        return outer in (parent.id, system.id if system else None)

    def _read_relationships(self, rel: str, rows: List[Tuple[int, List[str]]]) -> None:
        for line, cells in rows:
            if len(cells) != len(RELATIONSHIPS_HEADER):
                self.report(
                    rel, line, "REL01", f"the row has {len(cells)} cells; the header has {len(RELATIONSHIPS_HEADER)}"
                )
                continue
            source, target, technology, description = cells
            if not description:
                self.report(rel, line, "REL01", f"the relationship from `{source}` to `{target}` has an empty `Description`")
            joins = self.elements_read
            if self.elements_read:
                for end in dict.fromkeys((source, target)):
                    if end not in self.elements:
                        joins = False
                        if end not in self.declared:
                            self.report(rel, line, "REL02", f"`{end}` is no element of the table")
                if joins and source == target:
                    joins = False
                    self.report(rel, line, "REL02", f"the relationship joins `{source}` with itself")
                elif joins and (self.inside(source, target) or self.inside(target, source)):
                    joins = False
                    inner, outer = (source, target) if self.inside(source, target) else (target, source)
                    self.report(rel, line, "REL02", f"`{inner}` is inside `{outer}`; a relationship joins two others")
                types = [self.elements[end].type for end in (source, target) if end in self.elements]
                if not technology and any(kind in INNER_TYPES for kind in types):
                    self.report(
                        rel, line, "REL03",
                        f"the relationship from `{source}` to `{target}` reaches a container or component "
                        "and needs `Technology`",
                    )
            self.relationships.append(Relationship(source, target, technology, description, line, joins))

    # -- views -------------------------------------------------------------------

    def _placed(self, element: Element) -> bool:
        """Whether an element can be drawn: a known type, a parent that fits, and a parent that can be drawn."""
        if element.type is None or not element.fits:
            return False
        parent = self.elements.get(element.parent) if element.type in INNER_TYPES else None
        return element.type not in INNER_TYPES or (parent is not None and self._placed(parent))

    def _system_of(self, element: Element) -> Element:
        """The software_system a container or component is inside; any other element is its own."""
        if element.type == "container":
            return self.elements[element.parent]
        if element.type == "component":
            return self.elements[self.elements[element.parent].parent]
        return element

    def views(self) -> List[View]:
        drawn = [element for element in self.elements.values() if self._placed(element)]
        lines = [
            (self.elements[r.source], self.elements[r.target], r.description, r.technology)
            for r in self.relationships
            if r.joins and self._placed(self.elements[r.source]) and self._placed(self.elements[r.target])
        ]
        top = [element for element in drawn if element.type not in INNER_TYPES]
        views = [View(
            "System context",
            "Scope: every person, software_system and external_system, and the relationships between them.",
            None, [], top, self._arrows(lines, lambda end: self._system_of(end), None),
        )]
        for system in (element for element in drawn if element.type == "software_system"):
            containers = [e for e in drawn if e.type == "container" and e.parent == system.id]
            if not containers:
                continue

            def in_system(end: Element, system: Element = system) -> Element:
                if end.type in INNER_TYPES and self._system_of(end) is not system:
                    return self._system_of(end)
                return self.elements[end.parent] if end.type == "component" else end

            views.append(self._boxed(
                "Containers", "containers", system, containers, self._arrows(lines, in_system, containers), drawn
            ))
        for container in (element for element in drawn if element.type == "container"):
            components = [e for e in drawn if e.type == "component" and e.parent == container.id]
            if not components:
                continue

            def in_container(end: Element, container: Element = container) -> Element:
                if end.type in INNER_TYPES and self._system_of(end) is not self._system_of(container):
                    return self._system_of(end)
                if end.type == "component" and end.parent != container.id:
                    return self.elements[end.parent]
                return end

            views.append(self._boxed(
                "Components", "components", container, components, self._arrows(lines, in_container, components),
                drawn,
            ))
        return views

    @staticmethod
    def _arrows(
        lines: List[Tuple[Element, Element, str, str]], replace: Any, inside: Optional[List[Element]],
    ) -> List[Tuple[str, str, str, str]]:
        """The relationships of a view after their ends were replaced: without those whose ends became one
        element, each drawn once, and in a view with a box only those with an end inside the box."""
        arrows: List[Tuple[str, str, str, str]] = []
        within = None if inside is None else {element.id for element in inside}
        for source, target, description, technology in lines:
            arrow = (replace(source).id, replace(target).id, description, technology)
            if arrow[0] == arrow[1] or arrow in arrows:
                continue
            if within is not None and arrow[0] not in within and arrow[1] not in within:
                continue
            arrows.append(arrow)
        return arrows

    def _boxed(
        self, title: str, what: str, box: Element, inside: List[Element], arrows: List[Tuple[str, str, str, str]],
        drawn: List[Element],
    ) -> View:
        reached = {end for arrow in arrows for end in arrow[:2]} - {element.id for element in inside}
        return View(
            f"{title} of {markdown_text(box.name)} (`{box.id}`)",
            f"Scope: the {what} of `{box.id}`, and the elements outside it that they have relationships with.",
            box, inside, [element for element in drawn if element.id in reached], arrows,
        )

    # -- schemas/ ----------------------------------------------------------------

    def _read_schemas(self) -> None:
        folder = self.root / "schemas"
        for name in self._names(folder):
            path, rel = folder / name, f"schemas/{name}"
            matched = SCHEMA_FILE.fullmatch(name)
            if matched and path.is_file():
                if self._outside(rel):
                    self.report(rel, 1, "SCH01", f"a link leads {rel} out of the package folder; it is not read")
                else:
                    self.schemas[matched.group(1)] = Schema(matched.group(1), rel)
            elif name == "instances" and path.is_dir():
                self._list_instances(path)
            elif not (name.endswith(".md") and path.is_file()):
                self.report(
                    rel, 1, "SCH01",
                    f"{rel} is not allowed in schemas/, which holds `<name>.schema.json`, Markdown files and `instances/`",
                )
        for rel, name, valid in self.instances:
            schema = self.schemas.get(name)
            if schema is None:
                self.report(rel, 1, "SCH01", f"{rel} names no schema of the package: schemas/{name}.schema.json")
            elif valid:
                schema.valid += 1
            else:
                schema.invalid += 1
        for schema in self.schemas.values():
            self._read_schema(schema)
        for schema in self.schemas.values():
            if schema.id is None:
                continue
            key = schema.id.partition("#")[0] if uri_reference(schema.id) else None
            if key is None:
                # No key: the schema cannot be found by its `$id`, and its own references are not resolved.
                schema.refs_ok = schema.bases_ok = False
                if schema.form_ok:
                    self.report(
                        schema.rel, 1, "SCH05", f"at the top level: `$id` \"{schema.id}\" cannot be read as a URI "
                        f"reference; the references of {schema.rel} are not resolved",
                    )
                continue
            if key in self.by_key:
                schema.form_ok = False
                self.report(
                    schema.rel, 1, "SCH02", f"`$id` {schema.id} is the `$id` of {self.by_key[key].rel} already"
                )
            else:
                schema.key = key
                self.by_key[key] = schema
        for schema in self.schemas.values():
            if schema.key is not None:
                self.resources[schema.key] = (schema, schema.data, "")
        for schema in self.schemas.values():
            if schema.key is not None:
                self._read_bases(schema)
        # The validator's library gets each schema with its `$id`s and references rewritten (see RESOURCE_PREFIX).
        referencing = self.libraries.referencing
        self.registry = referencing.Registry().with_resources(
            (self._token(schema.key), referencing.jsonschema.DRAFT202012.create_resource(schema.given))
            for schema in self.schemas.values() if schema.form_ok and schema.bases_ok
        ).crawl()
        for schema in self.schemas.values():
            if schema.form_ok:
                self._check_schema_refs(schema)
            wanting = [kind for kind, count in (("valid", schema.valid), ("invalid", schema.invalid)) if not count]
            if wanting:
                self.report(
                    schema.rel, 1, "SCH03",
                    f"{schema.rel} has no {' and no '.join(wanting)} instance in schemas/instances/",
                )
        self._check_instances()

    def _list_instances(self, folder: Path) -> None:
        for name in self._names(folder):
            rel = f"schemas/instances/{name}"
            matched = INSTANCE_FILE.fullmatch(name)
            if matched and (folder / name).is_file():
                if self._outside(rel):
                    self.report(rel, 1, "SCH01", f"a link leads {rel} out of the package folder; it is not read")
                else:
                    self.instances.append((rel, matched.group(1), matched.group(2) == "valid"))
            else:
                self.report(
                    rel, 1, "SCH01",
                    f"{rel} is not allowed in schemas/instances/, which holds `<name>.valid-<label>.json` and "
                    "`<name>.invalid-<label>.json`",
                )

    def _read_schema(self, schema: Schema) -> None:
        rel = schema.rel
        try:
            data = self._data(rel)
        except DataError as error:
            self.report(rel, error.line, "SCH02", f"{rel} {error.message}")
            return
        schema.data = data
        if not isinstance(data, dict):
            self.report(rel, 1, "SCH02", f"the top level of {rel} must be an object")
            return
        ok = True
        if data.get("$schema") != DIALECT:
            ok = False
            self.report(rel, 1, "SCH02", f"`$schema` must be \"{DIALECT}\"")
        if isinstance(data.get("$id"), str) and data["$id"]:
            schema.id = data["$id"]
        else:
            ok = False
            self.report(rel, 1, "SCH02", "`$id` must be a non-empty string")
        if "type" not in data:
            ok = False
            self.report(rel, 1, "SCH02", "`type` is missing")
        try:
            errors = self._meta_errors(data)
        except RecursionError:
            errors, ok = [], False
            self.report(rel, 1, "SCH02", f"{rel} is nested too deeply to be checked against the meta-schema")
        if errors:
            ok = False
            self.report(
                rel, 1, "SCH02",
                f"{rel} is not valid against the meta-schema of JSON Schema 2020-12: {describe_errors(errors)}",
            )
        schema.form_ok = ok

    def _validator_class(self) -> Any:
        """JSON Schema 2020-12 as the validator reads it: numbers at their exact value (`multipleOf` divides
        exactly, and a number written with a point is an integer when its value is whole), and patterns as
        ECMA-262 in its Unicode mode, through regress, wherever the validator uses one."""
        if self.validator is None:
            jsonschema = self.libraries.jsonschema
            error = jsonschema.exceptions.ValidationError
            draft = jsonschema.Draft202012Validator
            compiled: Dict[str, Any] = {}

            def found(pattern: str, text: str) -> bool:
                if pattern not in compiled:
                    written = ecma_pattern(pattern)
                    if written is None:
                        raise self.libraries.regress.RegressError("a lone surrogate is the operand of an escape")
                    compiled[pattern] = self.libraries.regress.Regex(written, "u")
                if SURROGATE.search(text):
                    raise LoneSurrogate(text)
                return compiled[pattern].find(text) is not None

            def is_regex(instance: Any) -> bool:
                if isinstance(instance, str):
                    found(instance, "")  # raises regress.RegressError when ECMA-262 does not accept it
                return True

            def multiple_of(validator: Any, divisor: Any, instance: Any, schema: Any) -> Iterator[Any]:
                if validator.is_type(instance, "number") and not is_multiple(instance, divisor):
                    yield error(f"{instance!r} is not a multiple of {divisor!r}")

            def integer(checker: Any, instance: Any) -> bool:
                if isinstance(instance, decimal.Decimal):
                    return instance == instance.to_integral_value()
                return bool(draft.TYPE_CHECKER.is_type(instance, "integer"))

            def pattern(validator: Any, value: Any, instance: Any, schema: Any) -> Iterator[Any]:
                if validator.is_type(instance, "string") and not found(value, instance):
                    yield error(f"{instance!r} does not match {value!r}")

            def pattern_properties(validator: Any, value: Any, instance: Any, schema: Any) -> Iterator[Any]:
                if not validator.is_type(instance, "object"):
                    return
                for each, subschema in value.items():
                    for key, item in instance.items():
                        if found(each, key):
                            yield from validator.descend(item, subschema, path=key, schema_path=each)

            def listed(extras: List[Any]) -> str:
                return f"{', '.join(repr(extra) for extra in extras)} {'was' if len(extras) == 1 else 'were'}"

            def additional_properties(validator: Any, value: Any, instance: Any, schema: Any) -> Iterator[Any]:
                if not validator.is_type(instance, "object"):
                    return
                named = schema.get("properties", {})
                patterns = schema.get("patternProperties", {})
                extras = [key for key in instance if key not in named and not any(found(each, key) for each in patterns)]
                if validator.is_type(value, "object"):
                    for extra in extras:
                        yield from validator.descend(instance[extra], value, path=extra)
                elif not value and extras:
                    if patterns:
                        joined = ", ".join(repr(each) for each in sorted(extras))
                        verb = "does" if len(extras) == 1 else "do"
                        yield error(f"{joined} {verb} not match any of the regexes: "
                                    f"{', '.join(repr(each) for each in sorted(patterns))}")
                    else:
                        yield error(f"Additional properties are not allowed ({listed(sorted(extras, key=str))} unexpected)")

            def evaluated(validator: Any, instance: Dict[Any, Any], schema: Any) -> Set[Any]:
                """The keys of an object that a schema evaluates, for `unevaluatedProperties`, by the same steps
                as the library's own keyword, with patterns read as above. A reference is looked up as the
                library's keyword looks it up, through the validator's resolver, which alone knows the dynamic
                scope a `$dynamicRef` resolves in; the library offers no public way to it."""
                if not isinstance(schema, dict):
                    return set()
                keys: Set[Any] = set()
                for keyword in ("$ref", "$dynamicRef"):
                    if isinstance(schema.get(keyword), str):
                        resolved = validator._resolver.lookup(schema[keyword])
                        keys |= evaluated(validator.evolve(schema=resolved.contents, _resolver=resolved.resolver),
                                          instance, resolved.contents)
                if isinstance(schema.get("properties"), dict):
                    keys |= schema["properties"].keys() & instance.keys()
                for keyword in ("additionalProperties", "unevaluatedProperties"):
                    if schema.get(keyword) is not None:
                        keys |= {key for key, item in instance.items()
                                 if validator.evolve(schema=schema[keyword]).is_valid(item)}
                if isinstance(schema.get("patternProperties"), dict):
                    keys |= {key for key in instance if any(found(each, key) for each in schema["patternProperties"])}
                if isinstance(schema.get("dependentSchemas"), dict):
                    for key, subschema in schema["dependentSchemas"].items():
                        if key in instance:
                            keys |= evaluated(validator, instance, subschema)
                for keyword in ("allOf", "oneOf", "anyOf"):
                    for subschema in schema.get(keyword, []):
                        if validator.evolve(schema=subschema).is_valid(instance):
                            keys |= evaluated(validator, instance, subschema)
                if "if" in schema:
                    if validator.evolve(schema=schema["if"]).is_valid(instance):
                        keys |= evaluated(validator, instance, schema["if"])
                        if "then" in schema:
                            keys |= evaluated(validator, instance, schema["then"])
                    elif "else" in schema:
                        keys |= evaluated(validator, instance, schema["else"])
                return keys

            def unevaluated_properties(validator: Any, value: Any, instance: Any, schema: Any) -> Iterator[Any]:
                if not validator.is_type(instance, "object"):
                    return
                seen = evaluated(validator, instance, schema)
                failing = [key for key in instance if key not in seen
                           and next(validator.descend(instance[key], value, path=key, schema_path=key), None) is not None]
                if failing and value is False:
                    yield error(f"Unevaluated properties are not allowed ({listed(sorted(failing, key=str))} unexpected)")
                elif failing:
                    yield error("Unevaluated properties are not valid under the given schema "
                                f"({listed(failing)} unevaluated and invalid)")

            # The meta-schema's `format: regex` asserted with the same reading; its other formats as the library has them.
            formats = jsonschema.FormatChecker(formats=draft.FORMAT_CHECKER.checkers)
            formats.checks("regex", raises=self.libraries.regress.RegressError)(is_regex)
            # Registered for the dialect of 2020-12 in this process, the library's public way to name the class
            # for a `$schema`: the library switches to the class registered for the `$schema` of every schema
            # it enters, the meta-schema's own parts and each schema file of the package, so they read numbers
            # and patterns in the same way.
            self.validator = jsonschema.validators.extend(
                draft,
                validators={
                    "multipleOf": multiple_of, "pattern": pattern, "patternProperties": pattern_properties,
                    "additionalProperties": additional_properties, "unevaluatedProperties": unevaluated_properties,
                },
                type_checker=draft.TYPE_CHECKER.redefine("integer", integer),
                format_checker=formats,
                version="draft2020-12-exact-numbers",
            )
        return self.validator

    def _meta_errors(self, value: Any) -> List[Any]:
        """The errors of a value against the meta-schema of JSON Schema 2020-12."""
        if self.meta is None:
            validator = self._validator_class()
            self.meta = validator(validator.META_SCHEMA, format_checker=validator.FORMAT_CHECKER)
        try:
            return list(self.meta.iter_errors(value))
        except LoneSurrogate as text:
            return [self.libraries.jsonschema.exceptions.ValidationError(text.reason())]

    def _token(self, named: str) -> str:
        """What the validator's library gets for a resource the checker names: see RESOURCE_PREFIX."""
        return self.tokens.setdefault(named, f"{RESOURCE_PREFIX}{len(self.tokens)}")

    def _read_bases(self, schema: Schema) -> None:
        """The references of a schema with their bases, and the subschemas its `$id`s name (SCH02, SCH05)."""
        refs, ids, odd = walk_schema(schema.data, schema.key)
        for pointer, named, value in ids:
            owner = self.resources.get(named)
            if owner is None:
                self.resources[named] = (schema, value, pointer)
            elif schema.form_ok:
                schema.form_ok = False
                where = f" at {place(owner[2])}" if owner[2] else ""
                self.report(
                    schema.rel, 1, "SCH02",
                    f"the `$id` at {place(pointer)} names {named}, which the `$id` of {owner[0].rel}{where} names already",
                )
        if not schema.form_ok:
            return
        for pointer, why in odd:
            schema.refs_ok = schema.bases_ok = False
            self.report(schema.rel, 1, "SCH05", f"at {place(pointer)}: {why}; the references of {schema.rel} are not resolved")
        if odd:
            return
        schema.refs = refs
        # A copy for the validator, in which every `$id` and reference names its resource by its token.
        given = copy.deepcopy(schema.data)
        given["$id"] = self._token(schema.key)
        for pointer, named, _ in ids:
            value_at(given, pointer)["$id"] = self._token(named)
        for pointer, key, ref, base in refs:
            if uri_reference(ref):
                named, fragment = join_uri(base, ref)
                value_at(given, pointer)[key] = self._token(named) + (f"#{fragment}" if "#" in ref else "")
        schema.given = given

    def _check_schema_refs(self, schema: Schema) -> None:
        """Resolve every reference against its base, as JSON Schema 2020-12 gives it, with the package's schemas
        only, and hold what it leads to to the meta-schema."""
        for pointer, key, ref, base in schema.refs:
            problem = self._schema_ref(schema, ref, base)
            if problem:
                schema.refs_ok = False
                self.report(schema.rel, 1, "SCH05", f"`{key}` \"{ref}\" at {place(pointer)} {problem}")

    def _schema_ref(self, schema: Schema, ref: str, base: str) -> Optional[str]:
        """None if a reference of a schema leads to a schema of the package, or into one that is reported itself."""
        if not uri_reference(ref):
            return "does not lead to a part of a schema of the package: it cannot be read as a URI reference"
        named, fragment = join_uri(base, ref)
        against = f" (read against {base})" if base != schema.key else ""
        nowhere = f"does not lead to a part of a schema of the package{against}"
        owner = self.resources.get(named)
        if owner is None:
            return f"{nowhere}; nothing is fetched"
        other, resource, _ = owner
        if not (other.form_ok and other.bases_ok):
            schema.refers_to.add(other.name)  # that schema is reported itself
            return None
        decoded = decode_percent(fragment)
        if decoded is None or decoded.startswith("/") or not fragment:
            # A JSON Pointer, followed by the same rule as in contracts.
            target, malformed, missing = follow_pointer(resource, fragment)
            if malformed:
                return malformed
            if missing is not None:
                return f"{nowhere}: `#{fragment}` finds nothing at `{missing}`"
        else:
            try:  # an anchor, which the validator's library finds as it finds it during validation
                target = self.registry.resolver().lookup(f"{self._token(named)}#{fragment}").contents
            except self.libraries.referencing.exceptions.Unresolvable:
                return f"{nowhere}; nothing is fetched"
        if other is not schema:
            schema.refers_to.add(other.name)
        reached = f"{named}#{fragment}" if fragment else named
        try:
            errors = self._meta_errors(target)
        except RecursionError:
            return f"leads to {reached}, which is nested too deeply to be checked against the meta-schema"
        if errors:
            return (f"leads to {reached}, which is not a schema: it is not valid against the meta-schema "
                    f"of JSON Schema 2020-12: {describe_errors(errors)}")
        return None

    def _check_instances(self) -> None:
        judged = {name for name, schema in self.schemas.items() if schema.form_ok and schema.refs_ok}
        changed = True
        while changed:  # a schema that refers to one that is not judged is not judged either
            left = {name for name in judged if self.schemas[name].refers_to <= judged}
            changed, judged = left != judged, left
        exceptions = self.libraries.referencing.exceptions
        for rel, name, valid in self.instances:
            schema = self.schemas.get(name)
            if schema is None:
                continue  # SCH01
            try:
                data = self._data(rel)
            except DataError as error:
                self.report(rel, error.line, "SCH04", f"{rel} {error.message}")
                continue
            if name not in judged:
                continue
            validator = self._validator_class()(schema.given, registry=self.registry)
            try:
                errors = list(validator.iter_errors(data))
            except exceptions.Unresolvable as error:
                # A reference the checker does not read, such as one inside data that a reference leads to.
                why = str(error)
                for named, token in sorted(self.tokens.items(), key=lambda item: -len(item[1])):
                    why = why.replace(token, named)
                self.report(rel, 1, "SCH04", f"{rel} cannot be validated against {schema.rel}: {shorten(why)}")
                continue
            except RecursionError:
                self.report(rel, 1, "SCH04", f"{rel} cannot be validated against {schema.rel}: the validation does not end")
                continue
            except LoneSurrogate as text:
                self.report(rel, 1, "SCH04", f"{rel} cannot be validated against {schema.rel}: {text.reason()}")
                continue
            if valid and errors:
                self.report(rel, 1, "SCH04", f"{rel} is meant to be valid but fails {schema.rel}: {describe_errors(errors)}")
            elif not valid and not errors:
                self.report(rel, 1, "SCH04", f"{rel} is meant to be invalid but validates against {schema.rel}")

    # -- api/ --------------------------------------------------------------------

    def _outside(self, rel: str) -> bool:
        """Whether a file of the package lies outside the package folder once links are resolved."""
        top = os.path.realpath(str(self.root))
        return os.path.commonpath([os.path.realpath(str(self.root / rel)), top]) != top

    def _read_contracts(self) -> None:
        folder = self.root / "api"
        files: List[str] = []
        for name in self._names(folder):
            path, rel = folder / name, f"api/{name}"
            if name.endswith(PIECE_FILES["api"]) and path.is_file():
                if self._outside(rel):
                    self.report(rel, 1, "API01", f"a link leads {rel} out of the package folder; it is not read")
                else:
                    files.append(rel)
            elif not (name.endswith(".md") and path.is_file()):
                self.report(
                    rel, 1, "API01",
                    f"{rel} is not allowed in api/, which holds contracts (`.yaml`, `.yml`, `.json`) and Markdown files",
                )
        used: Dict[str, Dict[str, str]] = {}  # namespace: operationId: where it stands first
        for rel in files:
            contract = Contract(rel)
            self.contracts.append(contract)
            try:
                data = self._data(rel)
            except DataError as error:
                self.report(rel, error.line, "API02", f"{rel} {error.message}")
                continue
            if not isinstance(data, dict):
                self.report(rel, 1, "API02", f"the top level of {rel} must be a mapping")
                continue
            self._check_contract(contract, data, used.setdefault(operation_id_namespace(rel), {}))

    def _check_contract(self, contract: Contract, data: Dict[Any, Any], used: Dict[str, str]) -> None:
        rel = contract.rel
        version = data.get("openapi")
        matched = OPENAPI_VERSION.fullmatch(version) if isinstance(version, str) else None
        if matched is None:
            self.report(rel, 1, "API03", "`openapi` must be a string 3.0.x, 3.1.x or 3.2.x")
        else:
            contract.version = version
        info = data.get("info")
        if not isinstance(info, dict):
            self.report(rel, 1, "API03", "`info` must be a mapping with `title` and `version`")
        else:
            for key in ("title", "version"):
                if not isinstance(info.get(key), str) or not info[key]:
                    self.report(rel, 1, "API03", f"`info.{key}` must be a non-empty string")
        # What a contract must hold follows its version: 3.0 requires `paths`; 3.1 and 3.2 require at least one of
        # `paths`, `components` and `webhooks`. Without one of the versions no member is asked for.
        minor = int(matched.group(1)) if matched is not None else None
        if "paths" in data and not isinstance(data["paths"], dict):
            self.report(rel, 1, "API03", "`paths` must be a mapping")
        elif minor == 0 and "paths" not in data:
            self.report(rel, 1, "API03", "`paths` must be a mapping: an OpenAPI 3.0 contract needs it")
        elif minor in (1, 2) and not any(isinstance(data.get(key), dict) for key in ("paths", "components", "webhooks")):
            self.report(rel, 1, "API03", f"an OpenAPI 3.{minor} contract needs at least one of `paths`, `components` "
                        "and `webhooks` as a mapping")
        if matched is not None:
            for pointer, operation in operations(data, int(matched.group(1))):
                found = operation.get("operationId") if isinstance(operation, dict) else None
                if not (isinstance(found, str) and found):
                    self.report(
                        rel, 1, "API04", f"the operation at {place(pointer)} needs an `operationId` that is a non-empty string"
                    )
                    continue
                contract.operation_ids.append(found)
                if found in used:
                    self.report(rel, 1, "API04", f"`operationId` `{found}` at {place(pointer)} is used already at {used[found]}")
                else:
                    used[found] = f"{rel} {place(pointer)}"
        # The contract is read from its place in the package; what would give it another base is not read.
        rebased = [(pointer, "`$id`") for pointer, _ in find_keys(data, "$id")]
        if matched is not None and matched.group(1) == "2" and "$self" in data:
            rebased.insert(0, ("", "`$self`"))
        for pointer, key in rebased:
            self.report(
                rel, 1, "API05", f"{key} at {place(pointer)} would give the contract another base than its place in the "
                f"package and is not read; the references of {rel} are not resolved",
            )
        if rebased:
            return
        for pointer, ref in find_refs(data):
            problem = self._contract_ref(rel, ref)
            if problem:
                self.report(rel, 1, "API05", f"`$ref` \"{ref}\" at {place(pointer)} {problem}")

    def _contract_ref(self, rel: str, ref: str) -> Optional[str]:
        """None if a `$ref` of the contract at `rel` has a plain form and leads to something inside the package.
        The reference is judged on its text as written, before anything in it is decoded."""
        if not uri_reference(ref):
            return "cannot be read as a reference: it is not a URI-reference by RFC 3986, and it is not read"
        if re.match(r"[A-Za-z][A-Za-z0-9+\-.]*:", ref) or ref.startswith("//"):
            return "is an absolute reference, which is not read in a contract; refer to a file by a path relative to api/"
        if not ref:
            return "is empty, which is not read; write `#` and a JSON Pointer, or a path relative to api/"
        if "?" in ref.split("#", 1)[0]:
            return "has a query (`?`), which is not read; a reference to a file is a path relative to api/"
        split = urlsplit(ref)
        path = decode_percent(split.path)
        if path is None:
            return "has a path whose percent-encoding does not decode as UTF-8, which is not read"
        if path.startswith("/"):
            return "begins with `/`, which is not read; a reference to a file is a path relative to api/"
        mark = "#" in ref
        if not path:
            target = self._data(rel)  # a place in the same contract
        else:
            inner = posixpath.normpath(posixpath.join(posixpath.dirname(rel), path))
            if inner == ".." or inner.startswith("../"):
                return "leads out of the package folder"
            if not (self.root / inner).is_file():
                return f"names no file of the package ({inner})"
            if any(part.startswith(".") for part in inner.split("/")):
                return f"leads to {inner}, a name that starts with a dot, which is not read"
            if self._outside(inner):
                return f"leads to {inner}, which a link leads out of the package folder; it is not read"
            if not mark:
                return None
            if not inner.endswith(PIECE_FILES["api"]):
                return f"has a fragment, but {inner} is neither JSON nor YAML"
            try:
                target = self._data(inner)
            except DataError as error:
                return f"leads into {inner}, which {error.message}"
        if not mark:
            return None
        _, malformed, missing = follow_pointer(target, split.fragment)
        if malformed:
            return malformed
        return None if missing is None else f"leads nowhere: `#{split.fragment}` finds nothing at `{missing}`"


def operation_id_namespace(rel: str) -> str:
    """The namespace in which an `operationId` must be unique, for the contract at `rel`. It is the one place
    that sets the scope: each contract file is a namespace of its own."""
    return rel


def operations(data: Dict[Any, Any], minor: int) -> List[Tuple[str, Any]]:
    """Every operation of a contract, with its JSON Pointer.

    Operations are the values of the HTTP methods of a path item (and for 3.2 of `query` and of every
    key of `additionalOperations`). Path items are the values of `paths`, `webhooks`, `components.pathItems`
    and of the callbacks of operations and of `components.callbacks`. Keys beginning with `x-` in `paths`
    and in a callback are extensions. A path item's own `$ref` is not followed, but the operations beside it
    are its own; a callback that holds `$ref` is a reference and is not followed. A contract is read only as
    plainly written, without YAML aliases, so nothing in it stands at two places or inside itself.
    """
    methods = HTTP_METHODS + (("query",) if minor == 2 else ())
    found: List[Tuple[str, Any]] = []

    def path_item(item: Any, pointer: str) -> None:
        if not isinstance(item, dict):
            return
        named = [(method, item[method]) for method in methods if method in item]
        extra = item.get("additionalOperations") if minor == 2 else None
        if isinstance(extra, dict):
            named += [(f"additionalOperations/{escape_token(key)}", value) for key, value in extra.items()]
        for where, operation in named:
            found.append((f"{pointer}/{where}", operation))
            if isinstance(operation, dict):
                callbacks(operation.get("callbacks"), f"{pointer}/{where}/callbacks")

    def callbacks(mapping: Any, pointer: str) -> None:
        if isinstance(mapping, dict):
            for name, callback in mapping.items():
                if isinstance(callback, dict) and "$ref" not in callback:
                    for expression, item in callback.items():
                        if not (isinstance(expression, str) and expression.startswith("x-")):
                            path_item(item, f"{pointer}/{escape_token(name)}/{escape_token(expression)}")

    for key, extensions in (("paths", True), ("webhooks", False)):
        mapping = data.get(key)
        if isinstance(mapping, dict):
            for name, item in mapping.items():
                if not (extensions and isinstance(name, str) and name.startswith("x-")):
                    path_item(item, f"/{key}/{escape_token(name)}")
    components = data.get("components")
    if isinstance(components, dict):
        items = components.get("pathItems")
        if isinstance(items, dict):
            for name, item in items.items():
                path_item(item, f"/components/pathItems/{escape_token(name)}")
        callbacks(components.get("callbacks"), "/components/callbacks")
    return found


def mermaid_text(text: str) -> str:
    """Text from the tables as Mermaid shows it literally: all but A-Z, a-z and space as entity codes."""
    return "".join(char if ("A" <= char <= "Z" or "a" <= char <= "z" or char == " ") else f"#{ord(char)};" for char in text)


def markdown_text(text: str) -> str:
    """Text that Markdown shows as written: a backslash before each character of ASCII punctuation."""
    return re.sub(r"([!-/:-@\[-`{-~])", r"\\\1", text)


# How each type of element is drawn: the opening and closing marks of its Mermaid node, and the legend.
NODE_SHAPES = {
    "person": ('(["', '"])', "rounded at both ends"),
    "software_system": ('["', '"]', "rectangle"),
    "external_system": ('[["', '"]]', "rectangle with a double line at each side"),
    "container": ('("', '")', "rectangle with rounded corners"),
    "component": ('{{"', '"}}', "hexagon"),
}


def build_views(package: Package) -> str:
    """The generated views of a full package: one Mermaid flowchart for each view of `c4.md`."""
    assert package.tier is not None, "views are drawn for a full package only"
    tier = package.tier
    numbers = {ident: number for number, ident in enumerate(tier.elements, 1)}
    out = [GENERATED_MARK, "", "# Views", ""]
    out += [
        "Drawn from `c4.md`, one diagram for each view. Each node shows the name, the type and technology "
        "in brackets, and the description of an element.",
        "",
        "| Shape or line | Means |",
        "|---|---|",
    ]
    out += [f"| {shape[2].capitalize()} | `{kind}` |" for kind, shape in NODE_SHAPES.items()]
    out += [
        "| Box with a title | the `software_system` or `container` whose view it is |",
        "| Arrow | a relationship, pointing from `From` to `To`, with its description and its technology in brackets |",
    ]

    def node(element: Element) -> str:
        opening, closing, _ = NODE_SHAPES[element.type or ""]
        kind = element.type + (f", {mermaid_text(element.technology)}" if element.technology else "")
        label = f"{mermaid_text(element.name)}<br/>[{kind}]<br/>{mermaid_text(element.description)}"
        return f"e{numbers[element.id]}{opening}{label}{closing}"

    for view in tier.views():
        out += ["", f"## {view.title}", "", view.scope, "", "```mermaid", "flowchart TB"]
        if view.box is not None:
            box = view.box
            # The title on one line, so that the elements inside the box leave it room.
            out.append(f'    subgraph b1["{mermaid_text(box.name)} [{box.type}]"]')
            out += [f"        {node(element)}" for element in view.inside]
            out.append("    end")
        out += [f"    {node(element)}" for element in view.outside]
        for source, target, description, technology in view.arrows:
            label = mermaid_text(description) + (f"<br/>[{mermaid_text(technology)}]" if technology else "")
            arrow = f'-->|"{label}"|' if label else "-->"
            out.append(f"    e{numbers[source]} {arrow} e{numbers[target]}")
        out.append("```")
    return "\n".join(out) + "\n"



# -- trace -----------------------------------------------------------------


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def build_trace(package: Package) -> str:
    """The generated overview: counts, requirement table and reverse indexes.

    It shows what the checks use: a field that was set aside is left out here as well.
    """
    requirements = package.of_kind("REQ")
    decisions = package.of_kind("D")
    open_points = package.of_kind("OP")
    out = [GENERATED_MARK, "", "# Trace", "", "## Counts", ""]
    out += ["| Kind | Count | Breakdown |", "|---|---|---|"]
    by_status = ", ".join(
        f"{sum(1 for r in requirements if r.get('status') == s)} {s}"
        for s in STATUSES if any(r.get("status") == s for r in requirements)
    )
    by_origin = ", ".join(
        f"{sum(1 for d in decisions if d.get('origin') == o)} {o}"
        for o in ORIGINS if any(d.get("origin") == o for d in decisions)
    )
    by_op = ", ".join(
        f"{sum(1 for p in open_points if p.get('status') == s)} {s}"
        for s in OP_STATUSES if any(p.get("status") == s for p in open_points)
    )
    out.append(f"| Requirements | {len(requirements)} | {by_status or '-'} |")
    out.append(f"| Decisions | {len(decisions)} | {by_origin or '-'} |")
    out.append(f"| Open points | {len(open_points)} | {by_op or '-'} |")
    out.append(f"| Risks | {len(package.of_kind('R'))} | - |")
    out += ["", "## Requirements", ""]
    out += [
        "| Requirement | Title | Parent | Status | Version | Priority | Decisions | Criteria |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for req in requirements:
        named = sorted(set(ids_in(" ".join(text for _, text in req.usable_body()), "D")))
        criteria = req.usable("acceptance_criteria")
        items = criteria.items if criteria else []
        # A criterion is mechanical by its `[how]`, read as the criterion rule reads it, not by later text.
        mechanical = sum(1 for _, text in items if is_mechanical(text))
        out.append(
            f"| {req.id} | {cell(req.title)} | {', '.join(ids_in(req.get('parent'), 'REQ')) or '-'} "
            f"| {req.get('status') or '-'} | {req.get('version') or '-'} "
            f"| {req.get('priority') or '-'} | {', '.join(named) or '-'} "
            f"| {mechanical} mechanical, {len(items) - mechanical} judgement |"
        )
    out += ["", "## Decisions to requirements", ""]
    out += ["| Decision | Title | Origin | Requirements |", "|---|---|---|---|"]
    for decision in decisions:
        users = [
            req.id for req in requirements
            if decision.id in ids_in(" ".join(text for _, text in req.usable_body()), "D")
        ]
        out.append(
            f"| {decision.id} | {cell(decision.title)} | {decision.get('origin') or '-'} "
            f"| {', '.join(users) or '-'} |"
        )
    out += ["", "## Open points", ""]
    out += ["| Open point | Title | Status | Decided by |", "|---|---|---|---|"]
    for point in open_points:
        out.append(
            f"| {point.id} | {cell(point.title)} | {point.get('status') or '-'} "
            f"| {', '.join(ids_in(point.get('decided_by'), 'D')) or '-'} |"
        )
    units: Dict[str, List[str]] = {}
    for req in requirements:
        for unit in req.get("units").split(";"):
            name = unit.strip().strip("`").strip()
            if name:
                units.setdefault(name, []).append(req.id)
    out += ["", "## Units to requirements", ""]
    out += ["| Unit | Requirements |", "|---|---|"]
    for name in sorted(units):
        out.append(f"| `{cell(name)}` | {', '.join(units[name])} |")
    if package.tier is not None:
        out += full_trace(package, package.tier)
    return "\n".join(out) + "\n"


def full_trace(package: Package, tier: FullTier) -> List[str]:
    """What `trace.md` lists for a full package after what every package has: ADRs, schemas, contracts."""
    out = ["", "## ADRs", ""]
    out += ["| ADR | Title | Status | Decided by | Superseded by |", "|---|---|---|---|---|"]
    for adr in package.of_kind("ADR"):
        decided = list(dict.fromkeys(ids_in(adr.get("accepted_by"), "D") + ids_in(adr.get("status_by"), "D")))
        successors = [
            ref for ref in ids_outside_brackets(adr.get("superseded_by"), package.any_id)
            if re.fullmatch(FULL_ID_PATTERNS["ADR"], ref)
        ]
        out.append(
            f"| {adr.id} | {cell(adr.title)} | {adr.get('status') or '-'} "
            f"| {', '.join(decided) or '-'} | {', '.join(successors) or '-'} |"
        )
    out += ["", "## Schemas", ""]
    out += ["| Schema | `$id` | Valid instances | Invalid instances |", "|---|---|---|---|"]
    for schema in tier.schemas.values():
        out.append(f"| `{schema.rel}` | {cell(one_line(schema.id or '-'))} | {schema.valid} | {schema.invalid} |")
    out += ["", "## API contracts", ""]
    out += ["| Contract | OpenAPI | Operations |", "|---|---|---|"]
    for contract in tier.contracts:
        out.append(
            f"| `{cell(name_shown(contract.rel))}` | {cell(one_line(contract.version or '-'))} "
            f"| {cell(one_line(', '.join(contract.operation_ids))) or '-'} |"
        )
    return out


