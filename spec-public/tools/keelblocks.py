CODE, QUOTED, BRACKETED = 1, 2, 4
QUOTING = CODE | QUOTED  # what a sentence quotes and does not say itself


def run_end(text: str, at: int) -> int:
    """The position after the run of backticks that starts at `at`."""
    while at < len(text) and text[at] == "`":
        at += 1
    return at


def closing_run(text: str, start: int, length: int) -> int:
    """The position after the next run of exactly `length` backticks, or 0 if there is none."""
    at = start
    while True:
        at = text.find("`", at)
        if at == -1:
            return 0
        end = run_end(text, at)
        if end - at == length:
            return end
        at = end


def closing_quote(text: str, start: int) -> int:
    """The position after the double quote that closes quoted text, or 0 if there is none.

    A quote mark inside inline code does not close it.
    """
    at = start
    while at < len(text):
        char = text[at]
        if char == '"':
            return at + 1
        if char == "`":
            end = run_end(text, at)
            at = closing_run(text, end, end - at) or end
        else:
            at += 1
    return 0


class Scan:
    """What is quoted in a value, found once, in one pass from left to right.

    Every check that looks for structure in a value (`shall`, the outline of a statement, commands,
    terms, the targets of a replacement) reads it through this class, so that all of them agree.
    Quoted is inline code, a run of backticks up to the next run of the same length, also across a
    line break, and text from one double quote to the next. Round brackets, nested ones included,
    are found as well; only the fields that name what is replaced read them. Code is found first,
    then quotes, then brackets: a bracket inside quoted text or inside code counts for nothing, and a
    quote mark inside code quotes nothing. A backslash means nothing.
    """

    def __init__(self, text: str) -> None:
        self.text = text
        self.kinds: List[int] = []  # for every character, the kinds of text it stands in
        self.code: List[Tuple[int, int, int]] = []  # inline code: start, end, length of its backtick runs
        size, at, depth, quote_end = len(text), 0, 0, 0
        while at < size:
            char, end = text[at], at + 1
            quoted = at < quote_end
            kind = (QUOTED if quoted else 0) | (BRACKETED if depth else 0)
            if char == "`":
                end = run_end(text, at)
                close = closing_run(text, end, end - at)
                if close:
                    self.code.append((at, close, end - at))
                    end, kind = close, kind | CODE
            elif quoted:
                pass  # inside quoted text nothing else opens or closes
            elif char == '"':
                quote_end = closing_quote(text, end)
                if quote_end:
                    kind |= QUOTED
            elif char == "(":
                depth, kind = depth + 1, kind | BRACKETED
            elif char == ")" and depth:
                depth -= 1
            self.kinds.extend([kind] * (end - at))
            at = end

    def without(self, kinds: int, filler: str = " ") -> str:
        """The text with every character of the given kinds replaced, line breaks kept."""
        return "".join(
            filler if kind & kinds and char != "\n" else char for char, kind in zip(self.text, self.kinds)
        )

    def code_texts(self) -> List[str]:
        """What stands between the backticks of each piece of inline code."""
        return [self.text[start + run:end - run] for start, end, run in self.code]


