def version_of(package: str, parts: int) -> Tuple[int, ...]:
    from importlib import metadata

    return tuple(int(part) for part in re.findall(r"[0-9]+", metadata.version(package))[:parts])


def release_of(package: str) -> Tuple[int, ...]:
    """A version such as `1.0.0rc2` as a tuple that orders pre-releases (a, b, rc) before their release."""
    from importlib import metadata

    found = re.match(r"([0-9]+)\.([0-9]+)\.([0-9]+)(?:(a|b|rc)([0-9]+))?", metadata.version(package))
    if found is None:
        return ()
    stage = {"a": 0, "b": 1, "rc": 2, None: 3}[found.group(4)]
    return tuple(int(part) for part in found.group(1, 2, 3)) + (stage, int(found.group(5) or 0))


