def is_date(value: str) -> bool:
    """Whether the value is a calendar date written YYYY-MM-DD."""
    if not DATE.match(value):
        return False
    try:
        datetime.date(*(int(part) for part in value.split("-")))
    except ValueError:
        return False
    return True


