def level2_parts(lines: List[Tuple[int, str, bool]]) -> List[Part]:
    parts: List[Part] = []
    for number, text, fenced in lines:
        heading = None if fenced else HEADING.match(text)
        if heading and len(heading.group(1)) == 2:
            parts.append(Part(heading.group(2).strip(), number, []))
        elif parts:
            parts[-1].body.append((number, text, fenced))
    return parts


