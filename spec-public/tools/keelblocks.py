@dataclass
class Field:
    value: str
    line: int
    items: List[Tuple[int, str]] = field(default_factory=list)
    lines: List[int] = field(default_factory=list)  # every line the field takes up

    def text(self) -> str:
        return " ".join([self.value] + [item for _, item in self.items]).strip()


@dataclass
class Entry:
    kind: str
    id: str
    title: str
    rel: str
    line: int
    fields: Dict[str, Field] = field(default_factory=dict)
    body: List[Tuple[int, str]] = field(default_factory=list)
    bad: Set[str] = field(default_factory=set)  # fields set aside: reported as wrong in themselves
    repeated: List[Field] = field(default_factory=list)  # the further copies of a field given twice

    def usable(self, name: str) -> Optional[Field]:
        """The field, unless it is absent or was set aside as unknown, empty or malformed."""
        return None if name in self.bad else self.fields.get(name)

    def get(self, name: str) -> str:
        found = self.usable(name)
        return found.text() if found else ""

    def usable_body(self) -> List[Tuple[int, str]]:
        """The lines of the entry without the fields that were set aside."""
        aside = {number for name in self.bad for number in self.fields[name].lines}
        aside.update(number for found in self.repeated for number in found.lines)
        return [(number, text) for number, text in self.body if number not in aside]

    def line_of(self, name: str) -> int:
        found = self.fields.get(name)
        return found.line if found else self.line


@dataclass(frozen=True)
class Problem:
    rel: str
    line: int
    rule: str
    message: str


class InputError(Exception):
    """A package file cannot be read as the format requires."""


class Package:
    """All entries of one package plus the problems found while reading it."""

    def __init__(self, root: Path, libraries: Optional["Libraries"] = None) -> None:
        self.root = root
        self.entries: Dict[str, Entry] = {}
        self.problems: List[Problem] = []
        self.lines: List[Tuple[str, int, str]] = []
        self.glossary: Dict[str, int] = {}
        self.misplaced: Set[str] = set()
        # A package is full when its root holds architecture.md; only then are ADR ids ids.
        self.full = (root / "architecture.md").is_file()
        self.id_patterns = FULL_ID_PATTERNS if self.full else ID_PATTERNS
        self.any_id = ANY_FULL_ID if self.full else ANY_ID
        self.id_like = FULL_ID_LIKE if self.full else ID_LIKE
        self.libraries = libraries
        self.tier: Optional[FullTier] = None

    def read(self) -> None:
        """Read the package and judge its entries; after this the problems and the fields in use are known."""
        self.load()
        self.settle()
        if self.full:
            assert self.libraries is not None, "a full package is opened with its libraries"
            self.tier = FullTier(self, self.libraries)
            self.tier.read()

    def report(self, rel: str, line: int, rule: str, message: str) -> None:
        self.problems.append(Problem(rel, line, rule, message))

    def of_kind(self, kind: str) -> List[Entry]:
        return sorted((e for e in self.entries.values() if e.kind == kind), key=lambda e: e.id)

    # -- reading ---------------------------------------------------------

    def load(self) -> None:
        """Read every Markdown file of the package once; what a file may define follows from its place."""
        files: List[Tuple[str, Tuple[str, ...]]] = []
        for parts in self._markdown_files():
            rel = "/".join(parts)
            if rel == "decisions.md":
                files.append((rel, ("D", "OP", "R")))
            elif parts[0] == "requirements":
                files.append((rel, ("REQ",)))
            elif parts[0] == "adr" and self.full:
                files.append((rel, ("ADR",)))  # read as requirements/ is: every Markdown file below it
            else:
                files.append((rel, ()))  # defines nothing; read for references
        for rel, allowed in sorted(files):
            self._read(rel, allowed)
        self._read_glossary()

    def _markdown_files(self) -> List[Tuple[str, ...]]:
        """The path of every Markdown file to read, each folder once.

        The folders of the package come first and linked folders after them, so that a folder
        which is also reached through a link is read under its own name.
        """
        found: List[Tuple[str, ...]] = []
        seen: Set[str] = set()
        own: List[Tuple[Path, Tuple[str, ...]]] = [(self.root, ())]
        linked: List[Tuple[Path, Tuple[str, ...]]] = []
        for folders in (own, linked):
            for folder, parts in folders:  # grows while it is walked
                real = os.path.realpath(str(folder))
                if real in seen:
                    continue
                seen.add(real)
                for name in sorted(os.listdir(str(folder))):
                    here = parts + (name,)
                    # Not read: hidden files, the format description, the generated views, the script's folder.
                    if name.startswith(".") or here in self._not_read():
                        continue
                    path = folder / name
                    if path.is_dir():
                        (linked if path.is_symlink() else folders).append((path, here))
                    elif name.endswith(".md") and path.is_file():
                        found.append(here)
        return found

    def _not_read(self) -> Tuple[Tuple[str, ...], ...]:
        """The paths in the package root that are never read as package Markdown."""
        if self.full:
            return (("README.md",), ("trace.md",), ("views.md",), ("tools",))
        return (("README.md",), ("trace.md",), ("tools",))

    def _read(self, rel: str, allowed: Tuple[str, ...]) -> None:
        path = self.root / rel
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError as error:
            raise InputError(f"{path.as_posix()} is not valid UTF-8 (first bad byte at offset {error.start})")
        entry: Optional[Entry] = None
        current: Optional[Field] = None
        for number, line, fenced in read_lines(text):
            if fenced:
                continue
            self.lines.append((rel, number, line))
            heading = HEADING.match(line)
            if heading:
                entry, current = None, None
                if len(heading.group(1)) == 3:
                    entry = self._open_entry(rel, number, heading.group(2), allowed)
                elif allowed:
                    token = heading.group(2).partition(" ")[0]
                    if any(re.fullmatch(pattern, token) for pattern in self.id_patterns.values()):
                        self.report(rel, number, "ID02", f"{token}: an entry heading starts with `###`")
                        self.misplaced.add(token)  # declared, only badly: one report is enough
                continue
            if entry is None:
                continue
            entry.body.append((number, line))
            matched = FIELD.match(line)
            if matched:
                name, value = matched.group(1), (matched.group(2) or "").strip()
                if name in entry.fields:
                    self.report(rel, number, "FLD02", f"{entry.id}: field `{name}` is given twice")
                    current = Field(value, number, lines=[number])
                    entry.repeated.append(current)
                    entry.bad.add(name)  # which copy is meant is not known: none of them is used
                    continue
                current = Field(value, number, lines=[number])
                entry.fields[name] = current
                continue
            if current is None:
                continue
            item = SUB_ITEM.match(line)
            if item:
                current.items.append((number, (item.group(1) or "").strip()))
                current.lines.append(number)
                continue
            more = CONTINUATION.match(line)
            if more:
                current.lines.append(number)
                if current.items:
                    last_line, last_text = current.items[-1]
                    current.items[-1] = (last_line, f"{last_text} {more.group(1).strip()}")
                else:
                    current.value = f"{current.value} {more.group(1).strip()}".strip()
                continue
            current = None

    def _open_entry(self, rel: str, line: int, heading: str, allowed: Tuple[str, ...]) -> Optional[Entry]:
        token, _, title = heading.partition(" ")
        kind = next((k for k, p in self.id_patterns.items() if re.fullmatch(p, token)), None)
        if kind is None:
            if allowed and self.id_like.match(token):
                self.report(rel, line, "ID02", f"`{token}` is not a well-formed id")
            return None
        if kind not in allowed:
            # An entry is an entry wherever it stands; outside its file it defines nothing.
            self.report(rel, line, "ID03", f"{token}: a {KIND_NAMES[kind]} does not belong in {rel}")
            self.misplaced.add(token)
            return None
        if not title.strip():
            self.report(rel, line, "ID02", f"{token}: the heading has no title")
            self.misplaced.add(token)  # declared, only badly: one report is enough
            return None
        if token in self.entries:
            first = self.entries[token]
            self.report(rel, line, "ID01", f"{token} is already defined at {first.rel}:{first.line}")
            return None
        entry = Entry(kind, token, title.strip(), rel, line)
        self.entries[token] = entry
        return entry

    def _read_glossary(self) -> None:
        for rel, number, line in self.lines:
            if rel != "glossary.md" or not line.startswith("|"):
                continue
            cells = table_cells(line)
            first = cells[0]
            if not first or re.fullmatch(r"[-: ]+", first):
                continue  # an empty first cell, or the line of dashes below the heading
            term, plain = cell_term(first)
            if not plain:
                self.report(rel, number, "GLO02", f"the term `{first}` must be plain words or one piece of inline code")
            elif term and term.casefold() != "term" and len(cells) > 1 and cells[1]:
                self.glossary.setdefault(term.casefold(), number)  # not the heading, and with a meaning

    # -- checks ----------------------------------------------------------
    #
    # A report that names a field as wrong sets that field aside: no rule after it reads the field,
    # and the trace leaves it out. The first pass judges every field by itself (known, written once,
    # filled, written the way its row in the format description says). The second pass holds fields
    # and entries against each other and reads only the fields that are left. Terms are looked up
    # last, and the trace is built after both passes, from the fields that are still in use.

    def settle(self) -> None:
        """Both passes over the entries."""
        for entry in self.entries.values():
            self._check_fields(entry)
            self._check_forms(entry)
        for entry in self.of_kind("D"):
            self._check_decision(entry)
        for entry in self.of_kind("OP"):
            self._check_open_point(entry)
        for entry in self.of_kind("REQ"):
            self._check_requirement(entry)
        for entry in self.of_kind("ADR"):
            self._check_adr(entry)
        self._check_hierarchy()
        self._check_supersession()
        for entry in self.of_kind("REQ"):
            self._check_glossary_terms(entry)

    def reject(self, entry: Entry, name: str, line: int, rule: str, message: str) -> None:
        """Report a field as wrong and set it aside."""
        self.report(entry.rel, line, rule, message)
        entry.bad.add(name)

    def check(self, state_budget: int) -> None:
        wanted_trace = build_trace(self)
        for name in ("glossary.md", "state.md"):
            if not (self.root / name).is_file():
                self.report(name, 1, "PKG01", f"{name} is missing; run init to create it")
        self._check_references()
        self._check_state(state_budget)
        self._check_generated("trace.md", wanted_trace)
        if self.tier is not None:
            if not (self.root / "c4.md").is_file():
                self.report("c4.md", 1, "PKG02", "c4.md is missing; `init --tier full` writes it")
            self._check_generated("views.md", build_views(self))

    # -- first pass: each field by itself ----------------------------------

    def _check_fields(self, entry: Entry) -> None:
        """Missing, unknown and empty fields, a value beside a list, and values outside a fixed set."""
        spec = SPECS[entry.kind]
        known = spec.required + spec.optional
        for name in spec.required:
            if name not in entry.fields:
                self.report(entry.rel, entry.line, "FLD01", f"{entry.id}: field `{name}` is missing")
        for name, found in entry.fields.items():
            if name in entry.bad:
                continue  # given twice: reported where it was read, every copy set aside
            if name not in known:
                self.reject(entry, name, found.line, "FLD02", f"{entry.id}: unknown field `{name}`")
            elif not found.text():
                self.reject(entry, name, found.line, "FLD04", f"{entry.id}: field `{name}` is empty")
            elif found.value and found.items:
                self.reject(
                    entry, name, found.line, "FLD03",
                    f"{entry.id}: `{name}` has a value on its line and a list below it; write one or the other",
                )
        for name, allowed in spec.enums.items():
            found = entry.usable(name)
            if found is not None and found.text() not in allowed:
                self.reject(
                    entry, name, found.line, "FLD03",
                    f"{entry.id}: `{name}` is `{found.text()}`; allowed: {', '.join(allowed)}",
                )

    def _check_forms(self, entry: Entry) -> None:
        """Hold each field that has a form of its own against that form."""
        if entry.kind in ("D", "ADR"):
            date = entry.usable("date")
            if date is not None and not is_date(date.text()):
                self.reject(entry, "date", date.line, "FLD03", f"{entry.id}: `date` is not YYYY-MM-DD")
        if entry.kind == "OP":
            for name in ("decided_by", "status_by"):
                found = entry.usable(name)
                if found is not None and not ids_in(found.text(), "D"):
                    self.reject(entry, name, found.line, "OP01", f"{entry.id}: `{name}` names no decision")
        if entry.kind == "ADR":
            for name in ("accepted_by", "status_by"):
                found = entry.usable(name)
                if found is not None and not ids_in(found.text(), "D"):
                    self.reject(entry, name, found.line, "LIF03", f"{entry.id}: `{name}` names no decision")
                elif found is not None and VERSION_MARK.search(found.text()):
                    # Unlike a requirement's, the decision that accepts or sets aside an ADR carries no version.
                    self.reject(entry, name, found.line, "ADR03", f"{entry.id}: `{name}` carries a version; an ADR names "
                                "the owner decision alone, as `D-nnn`")
        if entry.kind in ("D", "REQ", "ADR"):
            self._check_replacement_form(entry)
        if entry.kind == "REQ":
            self._check_statement(entry)
            self._check_criteria(entry)
            self._check_numbers(entry)
            self._check_changes_form(entry)
            self._check_naming_forms(entry)

    def _check_replacement_form(self, entry: Entry) -> None:
        for name in ("supersedes", "superseded_by"):
            found = entry.usable(name)
            if found is None:
                continue
            named = ids_outside_brackets(found.text(), self.any_id)
            others = [ref for ref in named if ref != entry.id and re.fullmatch(self.id_patterns[entry.kind], ref)]
            if not others or len(others) != len(named):
                self.reject(
                    entry, name, found.line, "SUP01",
                    f"{entry.id}: `{name}` must name another {KIND_NAMES[entry.kind]}",
                )

    def _check_statement(self, entry: Entry) -> None:
        found = entry.usable("statement")
        if found is None:
            return
        declared = entry.get("pattern")
        if not declared:
            return  # without a usable pattern there is no shape to compare with
        # Quoted text (code, double quotes) is left out first: nothing in it counts.
        plain = Scan(found.text()).without(QUOTING, "x")
        if declared == "story":
            if not plain.endswith("."):
                self.reject(entry, "statement", found.line, "EARS02", f"{entry.id}: end the story with a full stop")
            elif not is_story(plain):
                self.reject(
                    entry, "statement", found.line, "EARS01",
                    f"{entry.id}: pattern `story` expects: {SHAPES['story']}",
                )
            return
        response = plain.partition(" shall ")[2]
        if len(SHALL.findall(plain)) != 1 or not plain.endswith(".") or not re.search(r"[^\W_]", response):
            self.reject(
                entry, "statement", found.line, "EARS02",
                f"{entry.id}: write `shall` exactly once with a response after it, and end the statement "
                "with a full stop",
            )
        elif ears_pattern_of(plain) != declared:
            self.reject(
                entry, "statement", found.line, "EARS01",
                f"{entry.id}: pattern `{declared}` expects: {SHAPES[declared]}",
            )

    def _check_criteria(self, entry: Entry) -> None:
        found = entry.usable("acceptance_criteria")
        if found is None:
            return
        if not found.items:
            self.reject(entry, "acceptance_criteria", found.line, "AC01", f"{entry.id}: no acceptance criterion")
        for position, (line, text) in enumerate(found.items, 1):
            matched = read_criterion(text)
            parts = [text[slice(*matched.span(group))] for group in (4, 5, 6)] if matched else []
            if not matched or not all(re.search(r"\S", part) for part in parts):
                self.reject(
                    entry, "acceptance_criteria", line, "AC01",
                    f"{entry.id}: write `ACn [mechanical: ...] GIVEN ... WHEN ... THEN ...` or use `[judgement]`",
                )
                continue
            if not names_number(matched.group(1), position):
                self.reject(
                    entry, "acceptance_criteria", line, "AC02",
                    f"{entry.id}: expected AC{position}, found AC{matched.group(1)}",
                )
            how = text[slice(*matched.span(3))] if matched.group(3) is not None else None
            if how is not None and not any(command.strip() for command in Scan(how).code_texts()):
                self.reject(
                    entry, "acceptance_criteria", line, "AC03",
                    f"{entry.id} AC{matched.group(1)}: name the command in backticks, or mark the criterion `[judgement]`",
                )

    def _check_numbers(self, entry: Entry) -> None:
        version = entry.usable("version")
        if version is not None and whole_number(version.text()) is None:
            self.reject(
                entry, "version", version.line, "FLD03", f"{entry.id}: `version` must be a whole number from 1"
            )
        priority = entry.usable("priority")
        if priority is not None and priority.text() not in ("1", "2", "3", "4", "5"):
            self.reject(entry, "priority", priority.line, "FLD03", f"{entry.id}: `priority` must be 1 to 5")

    def _check_changes_form(self, entry: Entry) -> None:
        changes = entry.usable("changes")
        if changes is None:
            return
        if not changes.items:
            self.reject(
                entry, "changes", changes.line, "VER01",
                f"{entry.id}: write `changes` as a list with one indented `- vN D-nnn: what changed` item per version",
            )
        for line, text in changes.items:
            if not CHANGE.match(text):
                self.reject(entry, "changes", line, "VER01", f"{entry.id}: write a change as `vN D-nnn: what changed`")

    def _binding_message(self, entry: Entry, name: str) -> str:
        version = whole_number(entry.get("version"))
        return (
            f"{entry.id}: `{name}` must name the decision and the version it is about, "
            f"here `D-nnn v{'N' if version is None else version}`"
        )

    def _check_naming_forms(self, entry: Entry) -> None:
        """Fields that name other entries: do they name any, and as many as the field takes."""
        source = entry.usable("source")
        if source is not None and not ids_in(source.text(), "D") and not ids_in(source.text(), "OP"):
            self.reject(entry, "source", source.line, "SRC01", SOURCE_MESSAGE.format(entry.id))
        for name in ("ratified_by", "accepted_by", "status_by"):
            found = entry.usable(name)
            if found is None:
                continue
            if not ids_in(found.text(), "D"):
                self.reject(entry, name, found.line, "LIF03", f"{entry.id}: `{name}` names no decision")
            elif name != "status_by" and len(VERSION_MARK.findall(found.text())) != 1:
                self.reject(entry, name, found.line, "VER02", self._binding_message(entry, name))
        parent = entry.usable("parent")
        if parent is not None:
            named = ids_in(parent.text(), "REQ")
            if len(named) != 1 or named[0] == entry.id:
                self.reject(
                    entry, "parent", parent.line, "HIE01", f"{entry.id}: `parent` must name one other requirement"
                )
            elif entry.get("pattern") == "story":
                self.reject(
                    entry, "parent", parent.line, "HIE01",
                    f"{entry.id}: a story is on the upper level and cannot have a parent",
                )

    # -- second pass: fields and entries against each other -----------------

    def _check_decision(self, entry: Entry) -> None:
        origin = entry.get("origin")
        if origin in ("owner", "constraint") and "quote" not in entry.fields:
            self.report(
                entry.rel, entry.line_of("origin"), "DEC01",
                f"{entry.id}: origin `{origin}` needs the owner's words in `quote`",
            )
        if origin == "derived" and "basis" not in entry.bad:
            basis = [i for i in ids_in(entry.get("basis"), "D") if i != entry.id]
            known = [self.entries[i] for i in basis if i in self.entries]
            rooted = [d for d in known if d.get("origin") in ("owner", "constraint")]
            judged = len(known) == len(basis) and all(d.get("origin") for d in known)
            if not rooted and judged:  # an undefined basis or one without a usable origin is reported there
                self.report(
                    entry.rel, entry.line_of("origin"), "DEC02",
                    f"{entry.id}: a derived decision needs `basis` naming the owner decision or constraint "
                    "it is derived from",
                )

    def _check_open_point(self, entry: Entry) -> None:
        status = entry.get("status")
        if not status:
            return  # missing or not allowed, and reported as that
        needed = {"decided": "decided_by", "parked": "status_by", "dropped": "status_by"}.get(status)
        for name in ("decided_by", "status_by"):
            if name in entry.bad:
                continue
            found = entry.fields.get(name)
            if found is None:
                if name == needed:
                    self.report(
                        entry.rel, entry.line_of("status"), "OP01",
                        f"{entry.id}: status `{status}` needs `{name}` naming the owner decision",
                    )
                continue
            if name != needed:
                self.reject(
                    entry, name, found.line, "OP01", f"{entry.id}: `{name}` does not go with status `{status}`"
                )
                continue
            for ref in ids_in(found.text(), "D"):
                decision = self.entries.get(ref)
                origin = decision.get("origin") if decision is not None else ""
                if origin and origin not in ("owner", "constraint"):
                    self.reject(
                        entry, name, found.line, "OP01",
                        f"{entry.id}: `{name}` names {ref}, which is not an owner decision or constraint",
                    )
                    break

    def _check_requirement(self, entry: Entry) -> None:
        status = entry.get("status")
        self._check_version_history(entry)
        source = entry.usable("source")
        if source is not None and not ids_in(source.text(), "D") and status and status != "draft":
            self.reject(entry, "source", source.line, "SRC01", SOURCE_MESSAGE.format(entry.id))
        if "priority" not in entry.fields and status in RATIFIED:
            self.report(
                entry.rel, entry.line, "FLD01",
                f"{entry.id}: field `priority` is missing (required for status `{status}`)",
            )
        if status in RATIFIED and "ratified_by" not in entry.fields:
            self.report(
                entry.rel, entry.line_of("status"), "LIF01",
                f"{entry.id}: status `{status}` needs `ratified_by`",
            )
        if status == "fulfilled" and "accepted_by" not in entry.fields:
            self.report(
                entry.rel, entry.line_of("status"), "LIF02",
                f"{entry.id}: `fulfilled` needs `accepted_by`; passing checks alone do not fulfil a requirement",
            )
        if status == "superseded" and "superseded_by" not in entry.fields:
            self.report(
                entry.rel, entry.line_of("status"), "LIF04",
                f"{entry.id}: `superseded` needs `superseded_by` naming the requirement that replaces it",
            )
        if status and status != "superseded" and entry.usable("superseded_by") is not None:
            self.report(
                entry.rel, entry.line_of("superseded_by"), "LIF04",
                f"{entry.id}: `superseded_by` names a replacement, so the status must be `superseded`, not `{status}`",
            )
        if status in ("parked", "descoped") and "status_by" not in entry.fields:
            self.report(
                entry.rel, entry.line_of("status"), "LIF05",
                f"{entry.id}: `{status}` needs `status_by` naming the owner decision",
            )
        version = whole_number(entry.get("version"))
        for name in ("ratified_by", "accepted_by", "status_by"):
            found = entry.usable(name)
            if found is None:
                continue
            origins = {ref: self.entries[ref].get("origin") for ref in ids_in(found.text(), "D") if ref in self.entries}
            other = [ref for ref, origin in origins.items() if origin and origin != "owner"]
            if other:
                self.reject(
                    entry, name, found.line, "LIF03",
                    f"{entry.id}: `{name}` names {other[0]}, which is not an owner decision",
                )
            elif name != "status_by" and version is not None and VERSION_MARK.findall(found.text()) != [str(version)]:
                self.reject(entry, name, found.line, "VER02", self._binding_message(entry, name))

    def _check_version_history(self, entry: Entry) -> None:
        version = whole_number(entry.get("version"))
        if version is None or "changes" in entry.bad:
            return  # reported as that
        changes = entry.usable("changes")
        got = [CHANGE.match(text).group(1) for _, text in (changes.items if changes else [])]
        if len(got) != version - 1 or any(not names_number(digits, place) for place, digits in enumerate(got, 2)):
            self.report(
                entry.rel, entry.line_of("version"), "VER01",
                f"{entry.id}: version {version} needs exactly one `changes` item for each version from 2 to {version}",
            )

    def _check_adr(self, entry: Entry) -> None:
        """The status of an ADR and the fields it needs, as a requirement's status is held to them."""
        status = entry.get("status")
        needed = {"accepted": ("accepted_by", "ADR01"), "rejected": ("status_by", "ADR02"),
                  "deprecated": ("status_by", "ADR02")}.get(status)
        if needed and needed[0] not in entry.fields:
            self.report(
                entry.rel, entry.line_of("status"), needed[1],
                f"{entry.id}: `{status}` needs `{needed[0]}` naming the owner decision",
            )
        if status == "superseded" and "superseded_by" not in entry.fields:
            self.report(
                entry.rel, entry.line_of("status"), "LIF04",
                f"{entry.id}: `superseded` needs `superseded_by` naming the ADR that replaces it",
            )
        if status and status != "superseded" and entry.usable("superseded_by") is not None:
            self.report(
                entry.rel, entry.line_of("superseded_by"), "LIF04",
                f"{entry.id}: `superseded_by` names a replacement, so the status must be `superseded`, not `{status}`",
            )
        for name in ("accepted_by", "status_by"):
            found = entry.usable(name)
            if found is None:
                continue
            origins = {ref: self.entries[ref].get("origin") for ref in ids_in(found.text(), "D") if ref in self.entries}
            other = [ref for ref, origin in origins.items() if origin and origin != "owner"]
            if other:
                self.reject(
                    entry, name, found.line, "LIF03",
                    f"{entry.id}: `{name}` names {other[0]}, which is not an owner decision",
                )

    def _check_glossary_terms(self, entry: Entry) -> None:
        if not (self.root / "glossary.md").is_file():
            return  # the missing file is reported once
        for line, marked in self._marked_terms(entry):
            term, plain = read_term(marked)
            if not plain:
                self.report(
                    entry.rel, line, "GLO02",
                    f"{entry.id}: `{' '.join(marked.split())}` is marked, but a marked term must be plain words "
                    "or one piece of inline code",
                )
            elif term and not any(form in self.glossary for form in term_forms(term)):
                self.report(
                    entry.rel, line, "GLO01",
                    f"{entry.id}: `{term}` is marked but has no row with a meaning in glossary.md",
                )

    @staticmethod
    def _marked_terms(entry: Entry) -> List[Tuple[int, str]]:
        """The text an entry writes in bold, each with the line it starts on.

        Bold stays within one block of lines: a field with the lines that continue its value, one item
        of a field's list with the lines that continue it, or a paragraph of the note, which a blank line
        ends and a line that begins a list item starts anew. Lines that are left out (a fenced code block,
        a field set aside) end a block too, so that a stray mark cannot reach text further down. Marks in
        inline code mark nothing.
        """
        part_of: Dict[int, Tuple[int, int]] = {}  # a line of a field: that field, and its value or item
        for found in list(entry.fields.values()) + entry.repeated:
            item_lines = {number for number, _ in found.items}
            part = found.line
            for number in sorted(found.lines):
                if number in item_lines:
                    part = number
                part_of[number] = (found.line, part)
        blocks: List[List[Tuple[int, str]]] = []
        last: Tuple[int, Optional[Tuple[int, int]]] = (0, None)
        for number, text in entry.usable_body():
            part = part_of.get(number)
            starts_block = (
                not text.strip() or (number - 1, part) != last
                or (part is None and LIST_ITEM.match(text) is not None)
            )
            if starts_block or not blocks:
                blocks.append([])
            blocks[-1].append((number, text))
            last = (number, part)
        marked: List[Tuple[int, str]] = []
        for block in blocks:
            scan = Scan("\n".join(text for _, text in block))
            solid = scan.without(CODE, "x")  # code is something, and its marks mark nothing
            for found in BOLD.finditer(solid):
                start, end = found.span(found.lastindex)
                marked.append((block[solid.count("\n", 0, found.start())][0], scan.text[start:end]))
        return marked

    def _finished(self, entry: Entry, seen: Tuple[str, ...] = ()) -> bool:
        """Whether a child no longer keeps its parent from being fulfilled."""
        status = entry.get("status")
        if status in ("fulfilled", "descoped"):
            return True
        if status != "superseded" or entry.id in seen:
            return False
        successors = [self.entries[ref] for ref in self._replacements(entry)]
        return bool(successors) and all(self._finished(s, seen + (entry.id,)) for s in successors)

    def _upper_entry(self, entry: Entry) -> Optional[Entry]:
        """The requirement an entry names as its parent, if it is defined."""
        found = entry.usable("parent")
        return self.entries.get(ids_in(found.text(), "REQ")[0]) if found else None

    def _check_hierarchy(self) -> None:
        children: Dict[str, List[Entry]] = {}
        # Looked up for all before any `parent` is set aside, so that the order of the entries does not matter.
        upper = {entry.id: self._upper_entry(entry) for entry in self.of_kind("REQ")}
        for entry in self.of_kind("REQ"):
            parent = upper[entry.id]
            if parent is None:
                continue  # no parent, one that was set aside, or an id that REF01 reports
            line = entry.line_of("parent")
            if upper[parent.id] is not None:
                self.reject(
                    entry, "parent", line, "HIE01",
                    f"{entry.id}: {parent.id} has a parent itself; the hierarchy has two levels",
                )
            elif parent.get("status") == "descoped":
                self.reject(
                    entry, "parent", line, "HIE01", f"{entry.id}: {parent.id} is descoped and cannot be a parent"
                )
            else:
                children.setdefault(parent.id, []).append(entry)
        for parent_id, group in children.items():
            parent = self.entries[parent_id]
            if parent.get("status") != "fulfilled":
                continue
            unfinished = [c.id for c in group if not self._finished(c)]
            if unfinished:
                self.report(
                    parent.rel, parent.line_of("status"), "HIE02",
                    f"{parent.id}: `fulfilled` while these children are unfinished: {', '.join(unfinished)}",
                )

    def _check_supersession(self) -> None:
        for entry in self.entries.values():
            for forward, back in (("supersedes", "superseded_by"), ("superseded_by", "supersedes")):
                found = entry.usable(forward)
                if found is None:
                    continue
                for ref in ids_outside_brackets(found.text(), self.any_id):
                    other = self.entries.get(ref)
                    if other is None:
                        continue  # REF01 reports the undefined id
                    answer = other.usable(back)
                    if answer is None and back in other.fields:
                        continue  # the other entry's own field was set aside and is reported there
                    if entry.id not in (ids_outside_brackets(answer.text(), self.any_id) if answer else []):
                        self.report(
                            entry.rel, found.line, "SUP01",
                            f"{entry.id} has `{forward}: {ref}`, but {ref} has no `{back}: {entry.id}`",
                        )
        self._check_replacement_circles()

    def _replacements(self, entry: Entry) -> List[str]:
        return [
            ref for ref in ids_outside_brackets(entry.get("superseded_by"), self.any_id)
            if ref != entry.id and ref in self.entries and self.entries[ref].kind == entry.kind
        ]

    def _replaced_through(self, entry: Entry) -> Set[str]:
        """Every entry reached by following `superseded_by` from this one."""
        reached: Set[str] = set()
        waiting = self._replacements(entry)
        while waiting:
            ref = waiting.pop()
            if ref not in reached:
                reached.add(ref)
                waiting.extend(self._replacements(self.entries[ref]))
        return reached

    def _check_replacement_circles(self) -> None:
        for entry in self.entries.values():
            reached = self._replaced_through(entry)
            if entry.id not in reached:
                continue
            circle = sorted(ref for ref in reached if entry.id in self._replaced_through(self.entries[ref]))
            if entry.id == circle[0]:  # one report for the circle, at its first entry
                self.report(
                    entry.rel, entry.line_of("superseded_by"), "SUP01",
                    f"{entry.id}: the replacements run in a circle: {', '.join(circle)}",
                )

    def _check_references(self) -> None:
        seen = set()
        for rel, number, line in self.lines:
            for ref in self.any_id.findall(line):
                defined = ref in self.entries or ref in self.misplaced
                if not defined and (rel, number, ref) not in seen:
                    seen.add((rel, number, ref))
                    self.report(rel, number, "REF01", f"{ref} is not defined")

    def _check_state(self, budget: int) -> None:
        path = self.root / "state.md"
        if path.is_file():
            size = path.stat().st_size
            if size > budget:
                self.report(
                    "state.md", 1, "STA01",
                    f"state.md has {size} bytes, budget {budget}: replace old content instead of adding to it",
                )

    def _check_generated(self, name: str, wanted: str) -> None:
        path = self.root / name
        if not path.is_file():
            self.report(name, 1, "GEN01", f"{name} is missing: run index")
        elif path.read_text(encoding="utf-8", errors="replace") != wanted:
            self.report(name, 1, "GEN01", f"{name} is out of date: run index")


def ids_in(text: str, kind: str, finder: re.Pattern = ANY_ID) -> List[str]:
    """Ids of one kind named in a field value, in order of appearance.

    `finder` finds the ids of the package's tier; ADR ids are found only by that of a full package.
    """
    pattern = re.compile(r"^" + FULL_ID_PATTERNS[kind] + r"$")
    return [ref for ref in finder.findall(text) if pattern.match(ref)]


def ids_outside_brackets(text: str, finder: re.Pattern = ANY_ID) -> List[str]:
    """All ids a field names; text in round brackets, nested ones included, only describes them."""
    return finder.findall(Scan(text).without(BRACKETED))


def whole_number(value: str) -> Optional[int]:
    """The value as a whole number from 1, or None if it is not written in up to nine plain digits."""
    return int(value) if re.fullmatch(r"[1-9][0-9]{0,8}", value) else None


def names_number(digits: str, number: int) -> bool:
    """Whether written decimal digits name a number as `int` reads them, leading zeros and the decimal digits of other
    scripts included, compared digit by digit so that a number of any length is read without turning it into an int."""
    return "".join(str(unicodedata.decimal(digit)) for digit in digits).lstrip("0") == str(number).lstrip("0")


def read_criterion(text: str) -> Optional[re.Match[str]]:
    """A criterion read the way the format writes it, or None if it does not have that form.

    The words that divide it count outside inline code only, so a command may hold them. The match is
    made on the text with its inline code blanked out, so its spans fit the text itself.
    """
    return CRITERION.match(Scan(text).without(CODE, "x"))


def is_mechanical(criterion: str) -> bool:
    """Whether the criterion's `[how]` names a command, as the criterion rule reads it."""
    matched = read_criterion(criterion)
    return matched is not None and matched.group(3) is not None


def is_story(statement: str) -> bool:
    matched = STORY.match(statement)
    return bool(matched) and all(re.search(r"[^\W_]", part) for part in matched.groups())


def has_content(part: str) -> bool:
    """Whether a part of a statement's outline names something: a letter or digit besides a leading article."""
    return bool(re.search(r"[^\W_]", re.sub(r"^\s*(?:the|an?)\b", "", part, flags=re.IGNORECASE)))


def term_forms(term: str) -> List[str]:
    """The term as written plus its likely singular forms, for glossary lookup."""
    low = term.strip().casefold()
    forms = [low]
    if low.endswith("ies"):
        forms.append(low[:-3] + "y")
    if low.endswith("es"):
        forms.append(low[:-2])
    if low.endswith("s"):
        forms.append(low[:-1])
    return forms


def is_plain(term: str) -> bool:
    """Whether a term is written in plain words, so that Markdown shows it as it is written."""
    if NOT_PLAIN.search(term):
        return False
    for run in re.finditer(r"_+", term):
        start, end = run.span()
        if start == 0 or end == len(term) or not term[start - 1].isalnum() or not term[end].isalnum():
            return False  # an underscore stays an underscore only between two letters or digits
    return True


def read_term(text: str) -> Tuple[str, bool]:
    """The term that the text between bold marks stands for, and whether it can be read.

    Line breaks and runs of spaces are one space. Italic marks around the whole are taken off. One
    piece of inline code as a whole stands for what it holds; anything else must be plain words.
    """
    term = " ".join(text.split())
    italic = WHOLE_ITALIC.fullmatch(term)
    if italic:
        term = italic.group(2)
    scan = Scan(term)
    if len(scan.code) == 1 and scan.code[0][:2] == (0, len(term)):
        return " ".join(scan.code_texts()[0].split()), True
    return term, is_plain(term)


def cell_term(cell: str) -> Tuple[str, bool]:
    """The term the first cell of a glossary row stands for, read the way a requirement reads bold.

    Bold in the cell marks the term, and around it the cell may hold nothing but `*` and `_`. A cell
    without bold is read like the text between bold marks.
    """
    scan = Scan(cell)
    solid = scan.without(CODE, "x")  # code is something, and its marks mark nothing
    found = BOLD.search(solid)
    if found is None:
        return read_term(cell)
    if (solid[:found.start()] + solid[found.end():]).strip("*_"):
        return " ".join(cell.split()), False
    start, end = found.span(found.lastindex)
    return read_term(cell[start:end])


def ears_pattern_of(statement: str) -> Optional[str]:
    """The EARS pattern whose outline a statement with one `shall` follows, or None if it follows none.

    The statement comes without its quoted text, so that a word in a command or in a quoted message
    counts for nothing. Only the outline is read: sentences, clauses and triggers are not counted.
    """
    head = statement.partition(" shall ")[0]
    first = head.partition(" ")[0]
    lead = EARS_KEYWORDS.get(first)
    if lead is None:
        if THEN.match(head):
            return None  # `then` opens the system only after an `if`
        return "ubiquitous" if has_content(head) else None
    before, comma, system = head.rpartition(", ")
    if not comma:
        return None
    parts = [before[len(first):]]
    trigger = TRIGGER.search(before) if lead in ("state", "optional") else None
    if trigger:
        parts = [before[len(first):trigger.start()], before[trigger.end():]]
    then = THEN.match(system)
    if then:
        if lead != "unwanted" and not (trigger and trigger.group(1).lower() == "if"):
            return None  # `then` follows an `if` only
        system = system[then.end():]
    elif lead == "unwanted":
        return None
    if not has_content(system) or not all(has_content(part) for part in parts):
        return None
    return "complex" if trigger else lead


LINE_BREAK = re.compile(r"\r\n|\r|\n")  # the only line breaks of YAML 1.2, JSON and CommonMark
LINE_BREAK_BYTES = re.compile(rb"\r\n|\r|\n")


def split_lines(text: str) -> List[str]:
    """Lines broken only at CR, LF and CRLF, unlike `str.splitlines`, which also breaks at U+2028, U+2029, U+0085,
    U+000B, U+000C and U+001C to U+001E; as with it, a break at the end opens no further line."""
    lines = LINE_BREAK.split(text)
    if lines and lines[-1] == "":
        lines.pop()
    return lines


def read_lines(text: str) -> Iterator[Tuple[int, str, bool]]:
    """Every line of a Markdown file with its number and whether it belongs to a fenced code block.

    A fence opens with three or more backticks or tildes and closes with a line of the same
    character, at least as many of them, and nothing else; both fence lines belong to the block.
    """
    text = text[1:] if text.startswith("\ufeff") else text  # a byte order mark starts the first line, as no text of it
    fence = ""  # the opening fence while inside a fenced code block
    for number, line in enumerate(split_lines(text), 1):
        mark = FENCE.match(line)
        if fence:
            closes = mark and mark.group(1).startswith(fence)  # the same character, at least as often
            if closes and not mark.group(2).strip():
                fence = ""
            yield number, line, True
        elif mark:
            fence = mark.group(1)
            yield number, line, True
        else:
            yield number, line, False


def table_cells(line: str) -> List[str]:
    """The cells of a table row, read as a row of `glossary.md` is.

    Without the `|` the row begins with, and without a `|` at its end that has no backslash directly
    before it, the row is split at every `|` without a backslash directly before it. A `|` after a
    backslash stays in its cell, as in a Markdown table, and the backslash goes. Cells are trimmed.
    """
    row = line.rstrip()[1:]  # without the | the row begins with
    if row.endswith("|") and not row.endswith("\\|"):
        row = row[:-1]  # and without a | it ends with
    return [cell.replace("\\|", "|").strip() for cell in re.split(r"(?<!\\)\|", row)]


